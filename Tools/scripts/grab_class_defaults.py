def resolve_untagged_owner():
    """The three 'not reachable in the decoded graph' objects, placed by their outer chain.

    G3-06 walked the 15 `Playable_Batmobile*` packages and recorded each row's own `outer` path
    in `REMAINDER.json`, so ownership needs no new package read: the rows the record could not
    place are members of the class their `outer` names.
    """
    doc = json.load(open(os.path.join(OUT, "REMAINDER.json"), encoding="utf-8"))
    rows = doc["untagged"]["objects"]
    unk = [r for r in rows
           if str(r.get("relevance", {}).get("verdict", "")).upper().startswith("UNKNOWN")]
    out = []
    for r in unk:
        owner = r.get("outer")
        out.append(OrderedDict(
            package=r["package"], export=r["index"], name=r["name"],
            class_name=r.get("class"), size=r["size"], shape=r.get("shape", {}).get("kind"),
            outer=owner,
            verdict=("owned by `%s` - a member of that class, not a reference from it" % owner)
                    if owner else "no outer path recorded",
        ))
    owners = sorted({r["outer"] for r in out if r["outer"]})
    cls_rows = [OrderedDict(package=r["package"], export=r["index"], class_name=r.get("class"),
                            size=r["size"])
                for r in rows if r["name"] == UNKNOWN3_CLASS]
    return OrderedDict(objects=out, owners=owners, class_rows=cls_rows)


