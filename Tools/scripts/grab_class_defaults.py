def same_kind(layout_kind, tag_type):
    a = TAG_KIND.get(layout_kind, layout_kind)
    b = TAG_KIND.get(tag_type, tag_type)
    if a == b:
        return True
    return (a in NATIVE and b == "StructProperty") or (b in NATIVE and a == "StructProperty")


# ---------------------------------------------------------------- layout

class Layout:
    """The class chain and every (offset, kind, member) the BmSDK dump declares."""

    def __init__(self, doc, root):
        self.classes = doc["classes"]
        self.chain = []
        seen = set()
        cls = root
        while cls and cls not in seen:
            seen.add(cls)
            self.chain.append(cls)
            c = self.classes.get(cls)
            if not c:
                break
            cls = c.get("super")
        # per-class offset -> members, and a global offset -> [(class, member)]
        self._gen = None
        self._supers = {}
        self._super_ev = {}
        self.by_class = {}
        for c in self.chain:
            table = {}
            for p in self.classes.get(c, {}).get("properties", []):
                table.setdefault(p["offset"], []).append(p)
            self.by_class[c] = table
        self.sdk = self._sdk_index()

    def _sdk_index(self):
        """{(class, member, offset): {file, line, mask}} from the BmSDK .g.cs files.

        The bindings document every property as `<Kind>: <Name>` and then implement it against
        `Ptr + <offset>`; the getter's `& <mask>` is the bitfield mask.  Masks are read as signed
        decimal, so `-2147483648` is the top bit of the word.
        """
        index = {}
        for cls in self.chain:
            c = self.classes.get(cls)
            if not c or not c.get("file"):
                continue
            ns = (c.get("namespace") or "").split(".")[-1]
            path = os.path.join(BMSDK, ns, c["file"])
            if not os.path.isfile(path):
                continue
            lines = open(path, encoding="utf-8-sig").read().splitlines()
            for i, line in enumerate(lines):
                m = DOC_LINE.match(line)
                if not m:
                    continue
                kind, name = m.group(1), m.group(2)
                off = mask = None
                for probe in lines[i + 1:i + 60]:
                    if DOC_LINE.match(probe):
                        break
                    if "Ptr + " not in probe:
                        continue
                    p = PTR.search(probe)
                    if not p:
                        continue
                    if off is None:
                        off = int(p.group(1))
                    if kind == "BoolProperty" and "&" in probe:
                        mk = MASK.search(probe[probe.index("Ptr + "):])
                        if mk:
                            mask = int(mk.group(1)) & 0xFFFFFFFF
                            break
                if off is None:
                    continue
                index[(cls, name, off)] = {"file": os.path.join(ns, c["file"]),
                                           "line": i + 1, "mask": mask, "kind": kind}
        return index

    def resolve(self, offset, tag_type):
        """(owner, members, candidates) for one tag; members are the kind-compatible ones."""
        for cls in self.chain:
            members = self.by_class.get(cls, {}).get(offset, [])
            if not members:
                continue
            ok = [p for p in members if same_kind(p["kind"], tag_type)]
            return cls, ok, members
        return None, [], []

    def info(self, owner, member):
        """Layout evidence for one member: file:line plus the BMSDK_OFFSETS entry."""
        rec = self.sdk.get((owner, member["member"], member["offset"]))
        out = {"class": owner, "member": member["member"], "offset": member["offset"],
               "kind": member["kind"], "array_type": member.get("type"),
               "mask": member.get("mask")}
        if rec:
            out["file"] = rec["file"]
            out["line"] = rec["line"]
            if member.get("mask") is None and rec.get("mask") is not None:
                out["mask"] = rec["mask"]
                out["mask_source"] = "getter"
        return out

    def mask_conflicts(self):
        """Where the BMSDK entry carries a mask and the getter's mask disagrees."""
        bad = []
        for cls in self.chain:
            for p in self.classes.get(cls, {}).get("properties", []):
                if p["kind"] != "BoolProperty" or p.get("mask") is None:
                    continue
                rec = self.sdk.get((cls, p["member"], p["offset"]))
                if rec and rec.get("mask") is not None and rec["mask"] != p["mask"]:
                    bad.append({"class": cls, "member": p["member"], "offset": p["offset"],
                                "bmsdk": p["mask"], "getter": rec["mask"]})
        return bad

    def super_chain(self, cls):
        out, seen = [], set()
        while cls and cls not in seen:
            seen.add(cls)
            out.append(cls)
            cls = self.super_of(cls)
        return out

    def _gen_files(self):
        """{class name: .g.cs path} for the BmSDK tree (used only for classes outside the index)."""
        if self._gen is None:
            import glob as _glob
            self._gen = {}
            for p in _glob.glob(os.path.join(BMSDK, "**", "*.g.cs"), recursive=True):
                self._gen.setdefault(os.path.basename(p)[:-5], p)
        return self._gen

    def super_of(self, cls):
        """The class's parent. BMSDK_OFFSETS.json carries 41 classes; a referenced object's class
        is often outside that set, so fall back to the class declaration in its own .g.cs. The
        fallback only ever adds ancestry evidence, never a property."""
        if cls in self._supers:
            return self._supers[cls]
        sup = None
        c = self.classes.get(cls)
        if c:
            sup = c.get("super")
        else:
            path = self._gen_files().get(cls)
            if path:
                pat = re.compile(r"public partial class %s\s*:\s*([\w\.]+)" % re.escape(cls))
                for i, line in enumerate(open(path, encoding="utf-8-sig")):
                    m = pat.search(line)
                    if m:
                        sup = m.group(1).split(".")[-1]
                        self._super_ev[cls] = "%s:%d" % (os.path.basename(path), i + 1)
                        break
        self._supers[cls] = sup
        return sup

    def binding_props(self, cls):
        """Class-level `(offset, member, kind, mask)` for a class from its own .g.cs.

        Used for the classes `BMSDK_OFFSETS.json` does not index (41 classes only). A doc block
        belongs to the class when the nearest enclosing declaration above it is the class and
        not a `[StructLayout(...)]` record struct, so struct members never leak in.
        """
        path = self._gen_files().get(cls)
        if not path:
            return []
        lines = open(path, encoding="utf-8-sig").read().splitlines()
        class_line = None
        for i, line in enumerate(lines):
            if "public partial class " in line and ("class %s " % cls) in line:
                class_line = i
                break
        if class_line is None:
            return []
        # Brace depth decides what belongs to the class: its own properties sit at depth 1, a
        # nested `partial record struct`'s members at depth 2+.  Generated code puts no braces
        # in strings, so counting braces before the `//` comment is exact here.
        out, depth = [], 0
        for i in range(class_line, len(lines)):
            line = lines[i]
            m = DOC_LINE.match(line)
            if depth == 1 and m:
                enclose = True
            else:
                enclose = False
            cut = line.find("//")
            depth += (line if cut < 0 else line[:cut]).count("{") - \
                     (line if cut < 0 else line[:cut]).count("}")
            if not enclose or m is None:
                continue
            kind, name = m.group(1), m.group(2)
            off = mask = None
            for q in lines[i + 1:i + 60]:
                if DOC_LINE.match(q):
                    break
                if "Ptr + " not in q:
                    continue
                r = PTR.search(q)
                if r and off is None:
                    off = int(r.group(1))
                if kind == "BoolProperty" and "&" in q:
                    mk = MASK.search(q[q.index("Ptr + "):])
                    if mk:
                        mask = int(mk.group(1)) & 0xFFFFFFFF
                        break
            if off is None:
                continue
            out.append(OrderedDict(offset=off, member=name, kind=kind, mask=mask,
                                   file=os.path.basename(path), line=i + 1))
        return out

    def is_a(self, cls, want):
        return bool(cls) and bool(want) and want in self.super_chain(cls)


# ---------------------------------------------------------------- value formatting

def f(v, digits=9):
    """A float as the shortest text that round-trips the stored 32-bit value."""
    if v != v:
        return "nan"
    out = "%.*g" % (digits, v)
    if "e" not in out and "." not in out:
        out += ".0"          # 5 -> 5.0: a float slot reads as a float
    return out


def ref_text(tag):
    if not tag.get("value"):
        return "None"
    return "%s (%s)" % (tag.get("ref") or "index %d" % tag["value"], tag.get("ref_class"))


SCALAR_TYPES = {"float": "float", "int": "int", "byte": "int", "bool": "int",
                "IntPtr": "int"}


def as_float(i):
    return struct.unpack("<f", struct.pack("<I", i & 0xFFFFFFFF))[0]


def array_text(tag, member, lay):
    """Decode an array by its declared element type, with the element class as the oracle.

    The class layout names the element type (`SVehicleWheel`, `float`, `FLinearColor`), so the
    branch is chosen from it rather than from whatever the byte slice happens to look like: a
    4-byte int array whose values happen to be valid object indices is an int array.
    """
    count = tag.get("count")
    mtype = (member or {}).get("array_type") or ""
    scalar = SCALAR_TYPES.get(mtype)
    refs = tag.get("refs")
    if refs is not None and not scalar:
        names, verdict = [], ""
        for r in refs:
            base = (r["path"] or "").split(".")[-1] if r["path"] else "None"
            names.append("%s:%s" % (r["class"], base))
            if mtype and not (r["class"] and lay.is_a(r["class"], mtype)):
                verdict = " (element class is not a %s)" % mtype
        return "count=%d ref %s[%s]%s" % (count, "%s " % mtype if mtype else "",
                                           ", ".join(names), verdict)
    if scalar == "float":
        vals = tag.get("floats")
        if vals is None and refs is not None:
            vals = [as_float(r["index"]) for r in refs]
        if vals is not None:
            return "count=%d float [%s]" % (count, ", ".join(f(v) for v in vals))
    if scalar == "int":
        vals = tag.get("ints") or [r["index"] for r in refs or []]
        if vals:
            return "count=%d int [%s]" % (count, ", ".join(str(v) for v in vals))
    if count == 0:
        return "count=0 (empty array, %s)" % (mtype or "element type not declared")
    if tag.get("items") is not None:
        return "count=%d %s elements, stride %s, each a decoded tag list" % (
            count, mtype or "struct", tag.get("stride"))
    if tag.get("strings"):
        return "count=%d strings %s" % (count, tag["strings"])
    raw = tag.get("raw") or ""
    stride = tag.get("stride")
    if raw and stride and count and len(raw) >= count * stride and stride in (12, 16):
        per = stride // 4
        elems = [bytes.fromhex(raw)[i * stride:(i + 1) * stride] for i in range(count)]
        rows = ["[" + ", ".join(f(struct.unpack_from("<f", e, k * 4)[0])
                                 for k in range(per)) + "]" for e in elems]
        return "count=%d %s elements of %d B as %d floats each (member names not decoded): %s" % (
            count, mtype or "struct", stride, per, " ".join(rows))
    if raw:
        return ("count=%d x %s B, element layout UNKNOWN, raw %s"
                % (count, stride, raw[:64]))
    return "count=%s %s" % (count, raw[:48])


def struct_text(tag):
    if tag.get("props") is not None:
        inner = []
        for p in tag["props"]:
            inner.append(struct_member_text(p))
        return "%d nested props: %s" % (tag.get("nested", len(tag["props"])), "; ".join(inner))
    if tag.get("value") is not None:
        return "%s (raw %s)" % (tag["value"], tag.get("raw", "")[:32])
    if tag.get("floats"):
        return "raw %s = 4 floats %s (struct layout not decoded)" % (
            tag.get("raw", "")[:32], [f(v) for v in tag["floats"]])
    return "raw %s" % tag.get("raw", "")[:48]


def struct_member_text(p):
    t = p["type"]
    head = "0x%02x " % p["offset"] if "offset" in p else ""
    if t == "ArrayProperty":
        return head + "%s[array]=%d" % (p.get("name"), p.get("count", 0))
    if t == "FloatProperty":
        return head + f(p["value"])
    if t in ("IntProperty",):
        return head + str(p["value"])
    if t == "BoolProperty":
        return head + "word 0x%x" % p.get("bits", 0)
    if t == "VectorProperty":
        return head + "[%s]" % ", ".join(f(v) for v in p["value"])
    if t == "ByteProperty":
        return head + str(p.get("value"))
    if t in ("ObjectNCRProperty", "ObjectProperty"):
        return head + "obj:%s" % (p.get("ref") or p.get("value"))
    if p.get("name"):
        return head + "%s=%s" % (p["name"], p.get("value"))
    return head + "%s=%s" % (t, p.get("value"))


def bool_text(bits, members, word_offset):
    """Every member of one 32-bit word, from the word alone (payload = whole word)."""
    parts, unknown, used = [], [], 0
    for m in members:
        mask = m.get("mask")
        if mask is None:
            unknown.append(m["member"])
            continue
        used |= mask
        parts.append("%s=%s" % (m["member"], bool(bits & mask)))
    true = [p for p in parts if p.endswith("True")]
    false = [p for p in parts if p.endswith("False")]
    text = ""
    if true:
        text = ", ".join(true)
        if len(parts) > len(true):
            text += " (other %d false)" % len(false)
    else:
        text = "all %d false" % len(parts)
    left = bits & ~used & 0xFFFFFFFF
    if left:
        text += "; bits 0x%x set but no member declares them" % left
    if unknown:
        text += "; UNKNOWN mask for %s" % ", ".join(unknown)
    return text, left, unknown


