def decode_tag(n, tag, data, lay):
    rec = OrderedDict()
    rec["n"] = n
    rec["payload_at"] = tag.get("at")
    rec["offset"] = tag["offset"]
    rec["offset_hex"] = "0x%04x" % tag["offset"]
    rec["tag_type"] = tag["type"]
    owner, members, cands = lay.resolve(tag["offset"], tag["type"])
    rec["owner"] = owner
    rec["named"] = bool(owner and members)
    rec["candidates"] = [{"class": owner, "kind": p["kind"], "member": p["member"]}
                         for p in cands]

    if rec["named"]:
        rec["kind"] = members[0]["kind"]
        rec["members"] = []
        for m in members:
            info = lay.info(owner, m)
            if tag["type"] == "BoolProperty":
                bits = tag.get("bits", 0)
                mask = info.get("mask")
                info["value"] = bool(bits & mask) if mask is not None else None
                info["mask_hex"] = "0x%08x" % mask if mask is not None else None
            rec["members"].append(info)
        if len(members) == 1:
            rec["name"] = members[0]["member"]
        elif tag["type"] == "BoolProperty":
            bits = tag.get("bits", 0)
            true = [m["member"] for m in members
                    if m.get("mask") is not None and bits & m["mask"]]
            rec["name"] = (", ".join(true) + " (%d of %d bools in the word)"
                           % (len(true), len(members))) if true else \
                          "no bit set (%d bools in the word)" % len(members)
        else:
            rec["name"] = " | ".join(m["member"] for m in members)
    else:
        rec["kind"] = None
        rec["name"] = None
        rec["members"] = []
        rec["unresolved_at_offset"] = [
            {"class": c, "kind": p["kind"], "member": p["member"]}
            for c in lay.chain for p in lay.by_class[c].get(tag["offset"], [])]

    # ---- value
    t = tag["type"]
    if t == "FloatProperty":
        rec["value"] = tag["value"]
        rec["value_text"] = f(tag["value"])
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 4].hex()
        rec["label"] = "decoded"
    elif t in ("IntProperty",):
        rec["value"] = tag["value"]
        rec["value_text"] = str(tag["value"])
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 4].hex()
        rec["label"] = "decoded"
    elif t == "BoolProperty":
        bits = tag.get("bits", tag["value"])
        text, left, unknown = bool_text(bits, rec["members"], tag["offset"])
        rec["value"] = bits
        rec["word_hex"] = "0x%08x" % bits
        rec["value_text"] = text
        rec["unassigned_bits"] = left
        rec["unknown_masks"] = unknown
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 4].hex()
        rec["label"] = "derived" if not left and not unknown else "derived (partial)"
    elif t == "ByteProperty":
        rec["value"] = tag.get("value")
        rec["value_text"] = "%r (enum FName)" % tag.get("value")
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 8].hex()
        rec["label"] = "decoded"
    elif t == "NameProperty":
        rec["value"] = tag.get("value")
        rec["value_text"] = "%r" % tag.get("value")
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 8].hex()
        rec["label"] = "decoded"
    elif t in ("ObjectNCRProperty", "ObjectProperty", "ClassProperty"):
        rec["value"] = tag.get("value")
        rec["value_text"] = ref_text(tag)
        rec["ref"] = tag.get("ref")
        rec["ref_class"] = tag.get("ref_class")
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 4].hex()
        rec["label"] = "decoded"
    elif t == "VectorProperty":
        rec["value"] = tag["value"]
        rec["value_text"] = "[%s]" % ", ".join(f(v) for v in tag["value"])
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 12].hex()
        rec["label"] = "decoded"
    elif t in ("RotatorProperty",):
        rec["value"] = tag["value"]
        rec["value_text"] = str(tag["value"])
        rec["raw_hex"] = data[tag["at"]:tag["at"] + 12].hex()
        rec["label"] = "decoded"
    elif t == "ArrayProperty":
        # the info dict, not the raw BMSDK entry: it carries the declared element type
        member = rec["members"][0] if rec["members"] else None
        rec["value"] = {k: tag[k] for k in ("count", "stride", "floats", "ints", "refs",
                                           "items", "strings", "raw") if k in tag}
        rec["value_text"] = array_text(tag, member, lay)
        rec["label"] = ("decoded" if (tag.get("floats") is not None or tag.get("refs") is not None
                                      or tag.get("ints") is not None or tag.get("items") is not None)
                        else "decoded (element layout UNKNOWN)")
        rec["raw_hex"] = data[tag["at"]:tag["at"] + min(32, tag.get("size", 0))].hex()
    elif t == "StructProperty":
        rec["value"] = {k: tag[k] for k in ("size", "props", "nested", "raw", "floats") if k in tag}
        rec["value_text"] = struct_text(tag)
        rec["label"] = "decoded" if tag.get("props") is not None else "decoded (raw only)"
        rec["raw_hex"] = data[tag["at"]:tag["at"] + min(32, tag.get("size", 0))].hex()
    else:
        rec["value"] = None
        rec["value_text"] = "UNKNOWN tag type %s" % t
        rec["label"] = "UNKNOWN"

    # ---- source line for the note
    rec["source"] = tag_source(rec)
    # ---- oracle: does the target object's class agree with the declared member type?
    rec["oracle"] = (object_oracle(rec, lay)
                     if t in ("ObjectNCRProperty", "ObjectProperty", "ClassProperty")
                     else None)
    return rec


def tag_source(rec):
    if not rec["named"]:
        return "UNKNOWN: no %s member at class offset %d in %s" % (
            rec["tag_type"], rec["offset"], "RVehicleBatmobile chain")
    m = rec["members"][0]
    out = "%s:%s (off %d" % (m["file"], m["line"], m["offset"]) if m.get("file") else \
        "BMSDK_OFFSETS.json %s (off %d" % (m["class"], m["offset"])
    if m.get("mask_hex"):
        out += ", mask %s" % m["mask_hex"]
    return out + ")"


def object_oracle(rec, lay):
    """'ok' when the referenced object's class is the declared type or a subclass of it."""
    want = (rec["members"][0].get("array_type") or "") if rec["members"] else ""
    have = rec.get("ref_class")
    if not rec.get("value"):
        return {"verdict": "null-pointer", "declared": want, "actual": None}
    if not want or not have:
        return {"verdict": "no-type", "declared": want, "actual": have}
    if want == have or lay.is_a(have, want):
        return {"verdict": "ok", "declared": want, "actual": have}
    return {"verdict": "mismatch", "declared": want, "actual": have}


def read_cdo(spec, lay):
    path = os.path.join(COOKED, spec["package"] + ".upk")
    pkg = PartialPackage(path)
    idx = spec["export"]
    e = pkg.exports[idx - 1]
    data = pkg.data(idx)
    got_class = pkg.object_class(idx)
    if e["name"] != spec["object"].split(".")[-1] or got_class != spec["class"]:
        raise SystemExit("export %d of %s is %s/%s, expected %s/%s"
                         % (idx, spec["package"], e["name"], got_class,
                            spec["object"], spec["class"]))
    tags, end, why = U.walk_tags(pkg, data, 0, max_tags=20000)
    rows = [decode_tag(i + 1, t, data, lay) for i, t in enumerate(tags)]
    rec = OrderedDict()
    rec["role"] = spec["role"]
    rec["package"] = spec["package"]
    rec["file"] = spec["package"] + ".upk"
    rec["export"] = idx
    rec["object"] = spec["object"]
    rec["class"] = got_class
    rec["size"] = len(data)
    rec["class_size"] = lay.classes.get(got_class, {}).get("size")
    rec["tag_count"] = len(tags)
    rec["payload_end"] = end
    rec["stop"] = why
    rec["tail"] = data[end:].hex()
    rec["tags"] = rows
    rec["counts"] = count_rows(rows)
    return rec


def count_rows(rows):
    types, flags = {}, {}

    def bump(d, k):
        d[k] = d.get(k, 0) + 1
    for r in rows:
        bump(types, r["tag_type"])
        if not r["named"]:
            bump(flags, "unnamed")
        if r.get("label", "").startswith("derived"):
            bump(flags, "bool_word")
        if r.get("oracle") and r["oracle"]["verdict"] != "ok":
            bump(flags, "oracle_%s" % r["oracle"]["verdict"])
        if r.get("unassigned_bits"):
            bump(flags, "unassigned_bits")
        if "element layout UNKNOWN" in r.get("value_text", ""):
            bump(flags, "array_element_UNKNOWN")
    return {"types": dict(sorted(types.items())), "flags": dict(sorted(flags.items()))}


# ---------------------------------------------------------------- comparisons

def cmp_key(r):
    """What a tag's value *is*, for comparing the two streams.

    A pointer's target is a subobject of the CDO it belongs to, so the full path differs between
    the two default objects by construction (`Default__RVehicleBatmobile.SVehicleMesh` vs
    `Default__RVehicleBatmobileBase.SVehicleMesh`). The comparable value is the subobject's name
    inside its owner plus its class.
    """
    t = r["tag_type"]
    if t in ("ObjectNCRProperty", "ObjectProperty", "ClassProperty"):
        if not r.get("ref"):
            return ("ref", None, None)
        return ("ref", str(r["ref"]).split(".")[-1], r.get("ref_class"))
    v = r.get("value")
    if t == "ArrayProperty" and isinstance(v, dict) and v.get("refs"):
        return ("refs", tuple((x["class"], (x["path"] or "").split(".")[-1])
                              for x in v["refs"]))
    return ("val", r["value_text"])


def compare(sub, base):
    """Which values the subclass sets: offsets in both streams, and offsets in one only."""
    key = lambda r: (r["offset"], r["tag_type"])
    s = {key(r): r for r in sub["tags"]}
    b = {key(r): r for r in base["tags"]}
    same, same_sub, differ, only_sub, only_base = [], [], [], [], []
    for k in s:
        if k not in b:
            only_sub.append(s[k])
            continue
        a, c = s[k], b[k]
        row = OrderedDict(offset=k[0], tag_type=k[1], name=a["name"] or a["offset_hex"],
                          subclass=a["value_text"], base=c["value_text"])
        if a["value_text"] == c["value_text"]:
            same.append(row)
        elif cmp_key(a) == cmp_key(c):
            same_sub.append(row)
        else:
            differ.append(row)
    for k in b:
        if k not in s:
            only_base.append(b[k])
    order = lambda rows: sorted(rows, key=lambda r: r["offset"])
    return OrderedDict(
        shared=len(same) + len(same_sub) + len(differ),
        same=order(same), same_subobject=order(same_sub), differ=order(differ),
        only_subclass=len(only_sub), only_base=len(only_base),
        only_subclass_offsets=[r["offset"] for r in sorted(only_sub, key=lambda r: r["offset"])],
        only_base_offsets=[r["offset"] for r in sorted(only_base, key=lambda r: r["offset"])],
        subclass_tags_in_own_range=sum(1 for r in sub["tags"] if r["owner"] == sub["class"]),
        subclass_tags_in_ancestor_ranges=sum(1 for r in sub["tags"] if r["owner"] != sub["class"]),
    )


def declared_without_value(lay, seen, root):
    """Declared properties of the chain that neither CDO stream serialises."""
    out = OrderedDict()
    for cls in lay.super_chain(root):
        props = lay.classes.get(cls, {}).get("properties", [])
        missing = [p["member"] for p in props if p["offset"] not in seen]
        out[cls] = {"declared": len(props), "no_value": len(missing),
                    "no_value_members": missing if cls == "RVehicleBatmobile" else None}
    return out


