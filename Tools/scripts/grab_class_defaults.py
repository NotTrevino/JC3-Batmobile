#!/usr/bin/env python3
"""grab_class_defaults.py - decode the Batmobile's cooked class-default VALUES (G3-06b).

G3-06 concluded that the Batmobile's class-default values are "not shipped". They are: the cooked
class default object of the script class is an export of the shipped packages, and its payload is
a plain Batman default-property stream (the same FPropertyTagBat2 format `upk_read` already walks
for every archetype). This tool reads the two of them and decodes every tag:

    Startup.upk  export 7530   BmScript.Default__RVehicleBatmobile       978 B    93 tags
    BmGame.upk   export 10923  BmGame.Default__RVehicleBatmobileBase   3186 B   181 tags

**Naming rule (no guesses).** A tag carries only a byte offset into the native class layout and a
type id; it does not carry the property's name. The name therefore comes only from a class layout
that declares a property at exactly that offset with a compatible kind:

    RVehicleBatmobile -> RVehicleBatmobileBase -> RVehicle -> AkVehicle -> SVehicle -> Vehicle
                      -> Pawn -> Actor

The chain and every (offset, kind, member, mask) come from `BMSDK_OFFSETS.json` (generated by
`bmsdk_offsets.py` from the BmSDK-AK `.g.cs` bindings, MIT: each property is emitted with the
absolute object offset the engine linked it to, which is the same number space as
FPropertyTagBat2.Offset). A tag whose offset/kind matches no member is published as
`UNKNOWN (offset only)` with the candidates that were tried - never named by resemblance. For a
`BoolProperty` the payload is the whole 32-bit bitfield word, so the offset names a *set* of
members and each member's value is `word & mask`; masks come from the same two sources (the
BmSDK entry, or its getter when the entry omits the mask).

**Value classes used in the record** (the project's R4 vocabulary, docs/README):
    decoded   bytes read at a named payload offset of a named export
    derived   produced by a stated rule from decoded bytes (bool bit splitting, the
              subclass/base comparison, array element lists typed by the class layout)
    UNKNOWN   no layout evidence; what was tried is recorded next to it

**Two UNKNOWNs from `reports/review-G3-06.md` are closed here, not in REMAINDER.md** (that file is
frozen): U-2, the member names of the previously offset-only CDO component tags, falls out of the
same layout lookup; U-3, the three "not reachable in the decoded graph" untagged objects, is
resolved by ownership from the `Startup.upk` export table (`outer_index`), which is reprinted in
§6 of the note.

Read-only outside its own two outputs. Nothing here launches, attaches to or writes the game.

Usage:
    python Tools/scripts/grab_class_defaults.py --write
    python Tools/scripts/grab_class_defaults.py --check
"""
