def invariants(record, lay):
    """Everything --check asserts about the record, beyond byte equality."""
    bad = []
    sub = record["cdo"]["subclass"]
    base = record["cdo"]["base"]
    for rec, spec in ((sub, TARGETS[0]), (base, TARGETS[1])):
        if rec["tag_count"] != spec["expect_tags"]:
            bad.append("%s: %d tags, expected %d"
                       % (rec["object"], rec["tag_count"], spec["expect_tags"]))
        if rec["stop"] != "eof" or rec["tail"] != "0000":
            bad.append("%s: run ended %r with tail %r, expected eof on 0000"
                       % (rec["object"], rec["stop"], rec["tail"]))
        if rec["payload_end"] + 2 != rec["size"]:
            bad.append("%s: payload %d + terminator != %d bytes"
                       % (rec["object"], rec["payload_end"], rec["size"]))
        chain_size = max(lay.classes[c]["size"] for c in lay.chain if c in lay.classes)
        for r in rec["tags"]:
            if not (0 < r["offset"] < chain_size):
                bad.append("%s tag %d: offset %d outside the chain extent %d"
                           % (rec["object"], r["n"], r["offset"], chain_size))
            if not r["named"]:
                bad.append("%s tag %d: offset %d has no layout member"
                           % (rec["object"], r["n"], r["offset"]))
            if r.get("oracle") and r["oracle"]["verdict"] == "mismatch":
                bad.append("%s tag %d (%s): target class %s is not a %s"
                           % (rec["object"], r["n"], r["name"], r["oracle"]["actual"],
                              r["oracle"]["declared"]))
    if lay.mask_conflicts():
        bad.append("%d BMSDK/getter mask conflicts" % len(lay.mask_conflicts()))
    u3 = record["review_unknowns"]["u3"]["objects"]
    if len(u3) != 3:
        bad.append("%d rows are unresolved in REMAINDER.json, expected the 3 of UNKNOWN #3"
                   % len(u3))
    for o in u3:
        if not o["outer"]:
            bad.append("%s export %d has no outer path" % (o["package"], o["export"]))
    return bad


def serialise(record, text):
    return (json.dumps(record, indent=1) + "\n", text)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not (a.write or a.check):
        ap.error("choose --write or --check")
    record, lay, sub, base = build()
    text = md(record, lay)
    js, text = serialise(record, text)
    bad = invariants(record, lay)
    if a.check:
        fail = list(bad)
        for path, want in ((OUT_JSON, js), (OUT_MD, text)):
            if not os.path.exists(path):
                fail.append("%s is missing" % os.path.basename(path))
                continue
            if open(path, encoding="utf-8").read() != want:
                fail.append("%s is stale" % os.path.basename(path))
        if fail:
            print("FAIL")
            for line in fail:
                print("  - " + line)
            return 1
        print("OK %s %d tags / %s %d tags; layout %s; masks %d (%d conflicts); "
              "overrides %d, subclass-only %d, base-only %d; unnamed 0; md+json byte-identical "
              "to a fresh rebuild"
              % (sub["object"], sub["tag_count"], base["object"], base["tag_count"],
                 " -> ".join(lay.chain), record["layout"]["masks_from_getter"],
                 len(lay.mask_conflicts()), len(record["compare"]["differ"]),
                 record["compare"]["only_subclass"], record["compare"]["only_base"]))
        print("CHECK_EXIT=0")
        return 0
    os.makedirs(OUT, exist_ok=True)
    open(OUT_JSON, "w", encoding="utf-8", newline="\n").write(js)
    open(OUT_MD, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote CLASS_DEFAULTS.md and CLASS_DEFAULTS.json")
    print("  %s (%s export %d): %d tags, %d bytes, tail %s"
          % (sub["object"], sub["package"], sub["export"], sub["tag_count"], sub["size"],
             sub["tail"]))
    print("  %s (%s export %d): %d tags, %d bytes, tail %s"
          % (base["object"], base["package"], base["export"], base["tag_count"], base["size"],
             base["tail"]))
    print("  unnamed tags %d, oracle not-ok %d, unassigned bool bits %d, array element UNKNOWN %d"
          % (sum(r["counts"]["flags"].get("unnamed", 0) for r in (sub, base)),
             sum(v for k, v in sub["counts"]["flags"].items() if k.startswith("oracle_")) +
             sum(v for k, v in base["counts"]["flags"].items() if k.startswith("oracle_")),
             sum(r["counts"]["flags"].get("unassigned_bits", 0) for r in (sub, base)),
             sum(r["counts"]["flags"].get("array_element_UNKNOWN", 0) for r in (sub, base))))
    print("  overrides %d, same subobject %d, subclass-only %d, base-only %d"
          % (len(record["compare"]["differ"]), len(record["compare"]["same_subobject"]),
             record["compare"]["only_subclass"], record["compare"]["only_base"]))
    for line in bad:
        print("  WARN " + line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
