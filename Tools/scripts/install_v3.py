def receipt_rows() -> list[tuple[str, str]]:
    d = json.load(open(RECEIPT, encoding="utf-8"))
    return [(f["path"].replace("/", "\\"), f["sha256"].upper()) for f in d["files"]]


def render() -> str:
    rows = receipt_rows()
    body = ",\n".join(f"    @('{rel}', '{sha}')" for rel, sha in rows)
    text = HEADER.replace("__SIMROOT__", SIM_ROOT).replace("__ROWS__", body)
    return text.replace("\r\n", "\n")


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def tree(root: str) -> dict[str, str]:
    out = {}
    for dirpath, _d, files in os.walk(root):
        for name in files:
            p = os.path.join(dirpath, name)
            out[os.path.relpath(p, root).replace("\\", "/")] = sha256_file(p)
    return dict(sorted(out.items()))


def digest(t: dict[str, str]) -> str:
    return hashlib.sha256(json.dumps(sorted(t.items()), separators=(",", ":")).encode()).hexdigest()


def ps(action: str, gamedir: str, source: str = SRC) -> subprocess.CompletedProcess:
    return subprocess.run(
        [PWSH, "-NoProfile", "-File", OUT, "-Action", action, "-GameDir", gamedir,
         "-Source", source],
        capture_output=True, text=True)


_OWN: list[str] = []
_ROOT_BEFORE: bool | None = None


def own(path: str) -> str:
    _OWN.append(path)
    return path


def case_path(name: str) -> str:
    # scenario copies live INSIDE the simulation root; the F1 bypass copy is a sibling of it.
    # The pid keeps two concurrent --check runs (another agent, a retry) from sharing a tree.
    return os.path.join(SIM_ROOT, f"case_{os.getpid()}_{name}")


def prefix_path(name: str) -> str:
    return os.path.join(SIM_DIR, f"_dropzone_sim_rc2_v3_{name}_{os.getpid()}")


def make_case(name: str, mode: str, rows: list[tuple[str, str]]) -> str:
    case = own(case_path(name))
    shutil.rmtree(case, ignore_errors=True)
    drop = os.path.join(case, "dropzone")
    os.makedirs(drop)
    for rel, content in (("keep.txt", b"decoy-keep\n"),
                         ("editor/keep_me.bin", b"decoy-editor\n")):
        p = os.path.join(drop, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "wb").write(content)
    for rel, _sha in rows:
        if mode == "absent":
            continue
        d = os.path.join(drop, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(d), exist_ok=True)
        if mode == "same":
            shutil.copyfile(os.path.join(SRC, rel.replace("/", os.sep)), d)
        else:
            open(d, "wb").write(("stale:" + rel).encode())
    return case


def edit_manifest(case: str, fn) -> None:
    p = os.path.join(case, SNAP_NAME, "manifest.json")
    d = json.load(open(p, encoding="utf-8-sig"))
    fn(d)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        json.dump(d, f, indent=1)


def cleanup_own() -> list[str]:
    """Remove this run's copies and, if it is empty or was created by this run, the root too.

    The root is `E:\\Modding\\_dropzone_sim_rc2_v3` itself; leaving it behind is what the
    second review reported. A concurrent --check owns a different pid-suffixed set, so this
    never removes another run's case directories; `rmdir` only succeeds on an empty root.
    """
    own_paths = list(_OWN)
    for p in own_paths:
        shutil.rmtree(p, ignore_errors=True)
    _OWN.clear()
    if _ROOT_BEFORE is False:
        shutil.rmtree(SIM_ROOT, ignore_errors=True)
    elif os.path.isdir(SIM_ROOT):
        try:
            os.rmdir(SIM_ROOT)
        except OSError:
            pass
    left = [p for p in own_paths if os.path.exists(p)]
    if os.path.exists(SIM_ROOT):
        left.append(SIM_ROOT)
    return left


