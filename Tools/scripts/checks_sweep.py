"""checks_sweep.py - which `--check` scripts are red today, for a letter range.

Discovery: every `Tools/scripts/<letter>*.py` whose text contains `--check`
(case-insensitive first letter, so `batmobile_grab.py` lands in b), minus this
file itself.

Each one runs as

    uv run --with numpy --with scipy --with pillow --with pefile \
           --with capstone --with fsb5 python <guard> <script> --check

with a 300 s wall limit. `<guard>` is generated by this script into
`tmp/freebuff/scratch/checks_guard.py` and installs a `sys.addaudithook` that
refuses any write except under `tmp/`, the system temp dir, or a `__pycache__`
/ `.pyc` path. A `--check` that turns out to write anywhere else is recorded as
*skipped* with the blocked path, and its exit code is 77 -- nothing on disk
changes. Reads, including the read-only game data, are untouched.

Verdicts per row: `ok`, `real failure`, `missing dependency: <module>`,
`missing input file: <path>`, `skipped - writes outside tmp/: <path>`,
`timeout`.

Usage:
  python Tools/scripts/checks_sweep.py a g          # letters a..g
  python Tools/scripts/checks_sweep.py a-g
  python Tools/scripts/checks_sweep.py a g --only bm_audio.py,audit_g302.py
  python Tools/scripts/checks_sweep.py a g --jobs 6 --jsonl tmp/freebuff/scratch/sweep_a.jsonl
  python Tools/scripts/checks_sweep.py a g --md Working/Translation/CHECKS_SWEEP_A.md
  python Tools/scripts/checks_sweep.py --table tmp/freebuff/scratch/sweep_a.jsonl  # reprint

Exit status is 0 only when every row is `ok`.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SCRATCH = os.path.join(ROOT, "tmp", "freebuff", "scratch")
GUARD = os.path.join(SCRATCH, "checks_guard.py")
SELF = os.path.basename(os.path.abspath(__file__))

UV = ["uv", "run", "--with", "numpy", "--with", "scipy", "--with", "pillow",
      "--with", "pefile", "--with", "capstone", "--with", "fsb5", "python"]
LIMIT = 300
GUARD_EXIT = 77
# Each run writes to a file, never a pipe: a timed-out `uv` leaves the real python
# holding pipe handles, and communicate() would then block forever. With files the
# wall limit is enforceable, and the tree is killed with `taskkill /T`.
LOGDIR = os.path.join(SCRATCH, "sweep_logs")
NEW_GROUP = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)

DEP = re.compile(r"(?:ModuleNotFoundError|ImportError): No module named '?([\w.]+)'?")
DEP2 = re.compile(r"No module named '?([\w.]+)'?")
MISS = re.compile(r"(?:FileNotFoundError|IOError|OSError): \[Errno 2\] "
                  r"No such file or directory: '([^']+)'")
MISS2 = re.compile(r"No such file or directory: '([^']+)'")
USAGE = re.compile(r"(?:unrecognized arguments|the following arguments are required|"
                   r"invalid choice|no such option)[^\n]*", re.I)
MISSING_GENERIC = re.compile(
    r"(?:missing|not found|does not exist|absent)[^\n]*?['`]([^'`\n]+\.(?:json|md|vmodc|rbm|ee|"
    r"toc|ddsc|effc|phys|pskx|bin|jsonl|xml))['`]", re.I)

GUARD_SRC = r'''"""Generated by Tools/scripts/checks_sweep.py: run one script with a tmp-only write guard.

Usage: python checks_guard.py <script.py> [args...]

Any write-mode open / rename / replace / remove / mkdir / rmtree outside
<root>/tmp, the system temp dir, or a __pycache__ / *.pyc path raises
PermissionError, which the sweep records as "skipped". This keeps a --check
mode from mutating Working/, Research/, Builds/ or the game data.
"""
import os
import runpy
import site
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
ALLOW = [os.path.join(ROOT, "tmp"), tempfile.gettempdir(), sys.prefix,
         sys.base_prefix, os.path.dirname(os.__file__)]
for _p in getattr(site, "getsitepackages", lambda: [])():
    ALLOW.append(_p)
for _p in (getattr(site, "getusersitepackages", lambda: "")() or "",):
    if _p:
        ALLOW.append(_p)
WRITE_FLAGS = os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_APPEND | os.O_TRUNC


def norm(p):
    # `open` reports an integer fd when it reopens one (FileIO(fd)); that fd was already
    # vetted when it was created, and os.fsdecode(int) raises TypeError.
    if isinstance(p, int):
        return ""
    return os.path.abspath(os.fsdecode(p)).replace("\\", "/").lower()


ALLOW_N = [norm(p) for p in ALLOW]


def allowed(p):
    n = norm(p)
    if n == "":
        return True
    if n.endswith(".pyc") or "/__pycache__/" in n or n.endswith("/__pycache__"):
        return True
    for a in ALLOW_N:
        if n == a or n.startswith(a + "/"):
            return True
    return False


def hook(event, args):
    if event == "open":
        path, mode, flags = (list(args) + [None, None, None])[:3]
        if path is None or isinstance(path, int):
            return
        write = bool(isinstance(mode, str) and any(c in mode for c in "wax+"))
        if mode is None and isinstance(flags, int) and flags & WRITE_FLAGS:
            write = True
        if write and not allowed(path):
            raise PermissionError("GUARD blocked write: " + os.fsdecode(path))
    elif event in ("os.rename", "os.replace", "os.remove", "os.rmdir", "os.mkdir",
                   "os.truncate", "shutil.copyfile", "shutil.copymode", "shutil.copystat",
                   "shutil.move", "shutil.rmtree", "os.chmod"):
        for a in args[:2]:
            if isinstance(a, (str, bytes, os.PathLike)) and not allowed(a):
                raise PermissionError("GUARD blocked write: " + os.fsdecode(a))


def main():
    if len(sys.argv) < 2:
        print("usage: checks_guard.py <script.py> [args...]", file=sys.stderr)
        return 2
    script = os.path.abspath(sys.argv[1])
    sys.argv = [script] + sys.argv[2:]
    sys.addaudithook(hook)
    try:
        runpy.run_path(script, run_name="__main__")
    except SystemExit as e:
        code = e.code
        if isinstance(code, int):
            return code
        if code is not None:
            print(str(code), file=sys.stderr)
        return 1
    except PermissionError as e:
        print(str(e), file=sys.stderr)
        return 77
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def ensure_guard() -> None:
    os.makedirs(SCRATCH, exist_ok=True)
    try:
        with open(GUARD, encoding="utf-8") as fh:
            if fh.read() == GUARD_SRC:
                return
    except OSError:
        pass
    with open(GUARD, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(GUARD_SRC)


def letters(start: str, end: str) -> list[str]:
    a, b = start.lower(), end.lower()
    return [chr(c) for c in range(ord(a), ord(b) + 1)]


def candidates(rng: list[str]) -> list[str]:
    names = []
    for n in sorted(os.listdir(HERE)):
        if not n.endswith(".py") or n == SELF:
            continue
        if n[0].lower() not in rng:
            continue
        try:
            with open(os.path.join(HERE, n), encoding="utf-8", errors="replace") as fh:
                if "--check" not in fh.read():
                    continue
        except OSError:
            continue
        names.append(n)
    return names


def clean(s: str) -> str:
    """The console is cp1252; a decoded dump can carry U+FFFD, which must not reach print()."""
    return s.replace("\ufffd", "?").encode("ascii", "replace").decode("ascii")


def tail(out: str, n: int = 2) -> list[str]:
    lines = [x.rstrip() for x in clean(out).splitlines() if x.strip()]
    return lines[-n:] if lines else ["(no output)"]


def classify(code: int, out: str) -> tuple[str, str]:
    if code == 0:
        return "ok", ""
    if code == GUARD_EXIT and "GUARD blocked write" in out:
        line = [x for x in out.splitlines() if "GUARD blocked write" in x][-1]
        return "skipped - writes outside tmp/", line.split("GUARD blocked write:", 1)[-1].strip()
    m = DEP.search(out) or DEP2.search(out)
    if m:
        return "missing dependency", m.group(1)
    m = MISS.search(out) or MISS2.search(out)
    if m:
        return "missing input file", m.group(1)
    m = MISSING_GENERIC.search(out)
    if m:
        return "missing input file", m.group(1)
    m = USAGE.search(out)
    if m:
        # The file mentions `--check` in prose but argparse rejects it: the check never ran.
        return "usage error - --check not accepted", m.group(0).strip()
    return "real failure", ""


def kill_tree(pid: int) -> None:
    """`uv` is the direct child; python, and anything python spawns, is not. Kill the tree."""
    if shutil.which("taskkill"):
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], capture_output=True,
                       stdin=subprocess.DEVNULL)
    else:
        subprocess.run(["pkill", "-9", "-P", str(pid)], capture_output=True)


def run_one(name: str) -> dict:
    cmd = UV + [GUARD, os.path.join(HERE, name), "--check"]
    os.makedirs(LOGDIR, exist_ok=True)
    path = os.path.join(LOGDIR, name + ".log")
    timed_out = False
    # PYTHONUNBUFFERED: a run killed at the wall limit must not lose the output that says where it
    # stopped. A blocked stdout would leave a 0-byte log and no way to tell a hang from a slow scan.
    env = dict(os.environ, PYTHONUNBUFFERED="1")
    with open(path, "wb") as fh:
        p = subprocess.Popen(cmd, cwd=ROOT, stdin=subprocess.DEVNULL, stdout=fh,
                             stderr=subprocess.STDOUT, creationflags=NEW_GROUP, env=env)
        try:
            code = p.wait(timeout=LIMIT)
        except subprocess.TimeoutExpired:
            kill_tree(p.pid)
            try:
                p.wait(timeout=30)
            except subprocess.TimeoutExpired:
                p.kill()
            code, timed_out = "TIMEOUT", True
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            out = fh.read()
    except OSError:
        out = ""
    if timed_out:
        t = tail(out)
        return {"script": name, "exit": "TIMEOUT",
                "tail": t if t != ["(no output)"] else [f"(no output before {LIMIT}s)"],
                "verdict": "timeout", "detail": f">{LIMIT}s"}
    verdict, detail = classify(code, out)
    return {"script": name, "exit": code, "tail": tail(out), "verdict": verdict,
            "detail": detail}


def cell(s: str, width: int = 0) -> str:
    s = clean(s.replace("|", "\\|"))
    return s[:width - 1] + "..." if width and len(s) > width else s


def row_md(r: dict, width: int = 0) -> str:
    t = cell(" / ".join(r["tail"]), width) or "(no output)"
    v = r["verdict"] + (f": `{r['detail']}`" if r["detail"] else "")
    return f"| `{r['script']}` | {r['exit']} | {t} | {v} |"


HEAD = "| script | exit | last two output lines | verdict |\n|---|---|---|---|"


def print_table(rows: list[dict], width: int = 0) -> None:
    print(HEAD)
    for r in rows:
        print(row_md(r, width))


def page(rows: list[dict], rng: list[str], width: int = 0) -> str:
    ok = [r for r in rows if r["verdict"] == "ok"]
    red = [r for r in rows if r["verdict"] != "ok"]
    guard = [r for r in red if r["verdict"].startswith("skipped")]
    dep = [r for r in red if r["verdict"] == "missing dependency"]
    miss = [r for r in red if r["verdict"] == "missing input file"]
    real = [r for r in red if r["verdict"] == "real failure"]
    use = [r for r in red if r["verdict"].startswith("usage")]
    slow = [r for r in red if r["verdict"] == "timeout"]
    L = []
    a = L.append
    a(f"# --check sweep, letters {rng[0]}..{rng[-1]}: `Tools/scripts/<letter>*.py`")
    a("")
    a(f"Generated by `python Tools/scripts/checks_sweep.py {rng[0]} {rng[-1]} --md "
      f"Working/Translation/CHECKS_SWEEP_A.md`.")
    a("")
    a("Selection: every `Tools/scripts/*.py` whose **first letter is in the range** and whose text")
    a("contains `--check` (this file excluded). Each ran as")
    a("")
    a("```")
    a("uv run --with numpy --with scipy --with pillow --with pefile --with capstone \\")
    a("       --with fsb5 python tmp/freebuff/scratch/checks_guard.py <script> --check")
    a("```")
    a("")
    a(f"under a {LIMIT} s wall limit, `stdin` closed, cwd = repo root. `checks_guard.py` is an")
    a("audit-hook wrapper that refuses any write outside `tmp/`, the system temp dir or a")
    a("`__pycache__/*.pyc` path, so a `--check` that turns out to write is recorded as *skipped*")
    a("with the blocked path instead of being allowed to touch `Working/`, `Research/`, `Builds/`")
    a("or the game data. Exit status for a blocked run is 77.")
    a("")
    a("Nothing was fixed, and no script or generated artefact was edited by the sweep.")
    a("")
    a("| candidates | ok | red | real failure | missing dependency | missing input file "
      "| usage error | skipped | timeout |")
    a("|---|---|---|---|---|---|---|---|---|")
    a(f"| {len(rows)} | {len(ok)} | {len(red)} | {len(real)} | {len(dep)} | {len(miss)} "
      f"| {len(use)} | {len(guard)} | {len(slow)} |")
    a("")
    if red:
        a("## Red rows")
        a("")
        a(HEAD)
        for r in red:
            a(row_md(r, width))
        a("")
    else:
        a("## Red rows")
        a("")
        a(f"None: all {len(rows)} scripts in this range exited 0.")
        a("")
    a("## Every row")
    a("")
    a(HEAD)
    for r in rows:
        a(row_md(r, width))
    a("")
    a("## Verdict key")
    a("")
    a("| verdict | meaning |")
    a("|---|---|")
    a("| `ok` | exit 0 |")
    a("| `real failure` | nonzero exit with no dependency or missing-file signature in its output |")
    a("| `missing dependency: X` | `ModuleNotFoundError: No module named 'X'` |")
    a("| `missing input file: P` | `FileNotFoundError` (or an explicit missing-file complaint) for `P` |")
    a("| `skipped - writes outside tmp/: P` | the write guard blocked a write to `P`; the check never ran |")
    a("| `usage error - --check not accepted` | argparse rejected `--check` (or demanded another "
      "argument), so the file only *mentions* `--check`; no check exists to run |")
    a("| `timeout` | exceeded the wall limit |")
    a("")
    return "\n".join(L)


def main(argv: list[str]) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001 - odd stream; clean() already sanitises
        pass
    if not argv:
        print(__doc__)
        return 2
    if argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    width = int(argv[argv.index("--width") + 1]) if "--width" in argv else 0
    if "--table" in argv:
        path = argv[argv.index("--table") + 1]
        rows = [json.loads(x) for x in open(os.path.join(ROOT, path), encoding="utf-8") if x.strip()]
        print_table(rows, width)
        return 0 if all(r["verdict"] == "ok" for r in rows) else 1
    if "--render" in argv:
        # re-render the page from a finished JSONL, no script runs
        src = os.path.join(ROOT, argv[argv.index("--render") + 1])
        rows = [json.loads(x) for x in open(src, encoding="utf-8") if x.strip()]
        rows.sort(key=lambda r: r["script"])
        rng = sorted({r["script"][0].lower() for r in rows})
        out = os.path.join(ROOT, argv[argv.index("--md") + 1])
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(page(rows, rng, width))
        print(f"re-rendered {os.path.relpath(out, ROOT)} from {len(rows)} row(s)")
        return 0

    args = [x for x in argv if not x.startswith("-")]
    if not args:
        print("need a letter range, e.g. a g", file=sys.stderr)
        return 2
    if "-" in args[0] and len(args[0]) == 3:
        start, end = args[0][0], args[0][2]
    else:
        start = args[0]
        end = args[1] if len(args) > 1 else args[0]
    rng = letters(start, end)
    names = candidates(rng)
    if "--only" in argv:
        want = {x.strip() for x in argv[argv.index("--only") + 1].split(",") if x.strip()}
        names = [n for n in names if n in want]
    if not names:
        print(f"no --check scripts under Tools/scripts for {start!r}..{end!r}")
        return 1

    ensure_guard()
    jobs = int(argv[argv.index("--jobs") + 1]) if "--jobs" in argv else 4
    jl_path = os.path.join(ROOT, argv[argv.index("--jsonl") + 1]) if "--jsonl" in argv else None
    rows: list[dict] = []
    if jl_path:
        os.makedirs(os.path.dirname(jl_path), exist_ok=True)
        if "--resume" in argv and os.path.exists(jl_path):
            with open(jl_path, encoding="utf-8") as fh:
                done = {r["script"]: r for r in (json.loads(x) for x in fh if x.strip())}
            rows = list(done.values())
            todo = [n for n in names if n not in done]
            print(f"resume: {len(rows)} recorded, {len(todo)} to run", flush=True)
            names = todo
        else:
            open(jl_path, "w", encoding="utf-8").close()
    # Stream each row to the JSONL as it lands: a killed sweep then resumes where it stopped.
    stream = open(jl_path, "a", encoding="utf-8", newline="\n") if jl_path else None
    with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
        for i, r in enumerate(ex.map(run_one, names), 1):
            rows.append(r)
            if stream:
                stream.write(json.dumps(r) + "\n")
                stream.flush()
            v = r["verdict"] + (f": `{r['detail']}`" if r["detail"] else "")
            print(f"[{i}/{len(names)}] {r['script']}\t{r['exit']}\t"
                  f"{clean(' / '.join(r['tail']))}\t{v}", flush=True)
    if stream:
        stream.close()
    rows.sort(key=lambda r: r["script"])

    print()
    print_table(rows)

    if "--jsonl" in argv:
        out = os.path.join(ROOT, argv[argv.index("--jsonl") + 1])
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            for r in rows:
                fh.write(json.dumps(r) + "\n")
    if "--md" in argv:
        out = os.path.join(ROOT, argv[argv.index("--md") + 1])
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(page(rows, rng, width))
        print(f"\npage: {os.path.relpath(out, ROOT)}")

    red = [r for r in rows if r["verdict"] != "ok"]
    print(f"\n{len(rows)} script(s), {len(red)} red.")
    return 0 if not red else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
