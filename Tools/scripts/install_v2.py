"""install_v2.py - generate and prove the bm-RC2 rollback fix (`Working/Installer/install_v2.ps1`).

Task 7231 found the defect in `Builds/bm-RC2/install.ps1`:

  * line 49 backs a target up only when it exists **and** its hash differs from the receipt;
  * line 66 makes `Rollback091` delete any target that has no backup.

On a dropzone that already holds the build, Install backs up nothing and Rollback091 then deletes
all nine payload files.  This card writes a **new** installer (the existing one and every existing
`Builds/` tree are untouched) with three rules:

  1. **always snapshot** every existing target before Install - same bytes or not - into
     `<GameDir>\\.install_v2_snapshot\\` with a `manifest.json` that records `existed`, `sha256`,
     `bytes` per target plus the directories Install had to create;
  2. **Rollback restores the snapshot** for every target that existed, and deletes only the
     targets the manifest records as absent before Install;
  3. **refuses to run** unless `-GameDir` is under the same simulation root task 7231 used
     (`E:\\Modding\\_dropzone_sim_rc2`), and refuses any path under a real game root.

`--check` regenerates the script byte-for-byte, compares its embedded rows with
`Builds/bm-RC2/receipt.json`, proves the three required scenarios on fresh copies under
`E:\\Modding\\_dropzone_sim_rc2_case_{a,b,c}`, and proves the guard refuses a non-sim path and a
fake game-root path without creating either.

    python Tools/scripts/install_v2.py --write
    python Tools/scripts/install_v2.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

RECEIPT = os.path.join(ROOT, "Builds", "bm-RC2", "receipt.json")
SRC = os.path.join(ROOT, "Builds", "bm-RC2", "drop")
OUT = os.path.join(ROOT, "Working", "Installer", "install_v2.ps1")
SIM_ROOT = r"E:\Modding\_dropzone_sim_rc2"
LIVE_DROP = r"D:\Games\Just Cause 3\dropzone"
PWSH = "pwsh"

HEADER = """<#
    bm-RC2 installer v2 - the rollback fix for B-14. Generated by Tools/scripts/install_v2.py
    --write, which also proves it on copies under E:\\Modding\\_dropzone_sim_rc2*. It never edits
    Builds/bm-RC2/install.ps1 and never installs into a real game folder.

    -Action Status     what the dropzone holds vs this receipt (read-only)
    -Action WhatIf     per target: add / replace / same, and whether a snapshot exists; writes 0 files
    -Action Install    ALWAYS snapshot every existing target, then copy the payload and re-hash
    -Action Verify     re-hash every target against the receipt (read-only)
    -Action Rollback   restore the snapshot byte-for-byte and delete only targets that did not exist
                       before Install; removes the snapshot afterwards

    Guard: -GameDir must be under __SIMROOT__ and must not be under a real game root,
    so a typo cannot reach the live install. Close the game before Install/Rollback.
#>
[CmdletBinding()]
param(
    [ValidateSet('Status','WhatIf','Install','Verify','Rollback')][string]$Action = 'Status',
    [string]$GameDir = '',
    [string]$Source = ''
)
$ErrorActionPreference = 'Stop'
$SimRoot   = '__SIMROOT__'
$DenyRoots = @('D:\\Games', 'E:\\Games')
$Files = @(
__ROWS__
)
function Refuse([string]$m) { Write-Output ('REFUSED: ' + $m); exit 2 }
function HashOf([string]$p) { (Get-FileHash -LiteralPath $p -Algorithm SHA256).Hash }
function EnsureDir([string]$p) {
    if (-not (Test-Path -LiteralPath $p)) { New-Item -ItemType Directory -Force -Path $p | Out-Null }
}

if ([string]::IsNullOrWhiteSpace($GameDir)) { Refuse '-GameDir is required' }
$full    = [IO.Path]::GetFullPath($GameDir).TrimEnd('\\')
$simFull = [IO.Path]::GetFullPath($SimRoot).TrimEnd('\\')
$cmp     = [StringComparison]::OrdinalIgnoreCase
if (-not ($full.Equals($simFull, $cmp) -or $full.StartsWith($simFull, $cmp))) {
    Refuse ('-GameDir ' + $full + ' is not under the simulation root ' + $simFull)
}
foreach ($d in $DenyRoots) {
    $dn = [IO.Path]::GetFullPath($d).TrimEnd('\\')
    if ($full.Equals($dn, $cmp) -or $full.StartsWith($dn + '\\', $cmp)) {
        Refuse ('-GameDir ' + $full + ' is inside a real game root ' + $dn)
    }
}
$Drop = Join-Path $full 'dropzone'
if (-not (Test-Path -LiteralPath $Drop)) { Refuse ('no dropzone under ' + $full) }
if ([string]::IsNullOrWhiteSpace($Source)) {
    $Source = Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) 'Builds\\bm-RC2\\drop'
}
$Snap     = Join-Path $full '.install_v2_snapshot'
$Manifest = Join-Path $Snap 'manifest.json'
$n = 0; $bad = 0

if ($Action -eq 'Status') {
    foreach ($f in $Files) {
        $rel = $f[0]; $sha = $f[1]
        $d = Join-Path $Drop $rel
        if (Test-Path -LiteralPath $d) {
            if ((HashOf $d) -eq $sha) { $st = 'installed' } else { $st = 'different' }
        } else { $st = 'absent' }
        Write-Output ($st + ' ' + $rel)
    }
    if (Test-Path -LiteralPath $Manifest) { Write-Output ('snapshot present ' + $Manifest) }
    else { Write-Output 'snapshot absent' }
}

if ($Action -eq 'WhatIf') {
    foreach ($f in $Files) {
        $rel = $f[0]; $sha = $f[1]
        $d = Join-Path $Drop $rel
        if (Test-Path -LiteralPath $d) {
            if ((HashOf $d) -eq $sha) { $op = 'same (snapshot, then overwrite)' }
            else { $op = 'replace (snapshot, then overwrite)' }
        } else { $op = 'add (no snapshot)' }
        Write-Output ($rel + ' ' + $sha + ' ' + $op)
    }
    Write-Output ('wrote 0 files, ' + $Files.Count + ' listed')
}

if ($Action -eq 'Install') {
    if (Test-Path -LiteralPath $Snap) {
        throw ('a snapshot already exists at ' + $Snap + ' - run Rollback first')
    }
    EnsureDir $Snap
    $snapFiles = @()
    $created = @()
    foreach ($f in $Files) {
        $rel = $f[0]; $sha = $f[1]
        $s = Join-Path $Source $rel
        if (-not (Test-Path -LiteralPath $s)) { throw ('build file missing: ' + $rel) }
        if ((HashOf $s) -ne $sha) { throw ('build file does not match the receipt: ' + $rel) }
        $d = Join-Path $Drop $rel
        $entry = [pscustomobject]@{ path = $rel; existed = $false; sha256 = ''; bytes = 0 }
        if (Test-Path -LiteralPath $d) {
            $entry.existed = $true
            $entry.sha256 = (HashOf $d)
            $entry.bytes  = (Get-Item -LiteralPath $d).Length
            $bak = Join-Path (Join-Path $Snap 'files') $rel
            EnsureDir (Split-Path -Parent $bak)
            Copy-Item -LiteralPath $d -Destination $bak -Force
            if ((HashOf $bak) -ne $entry.sha256) { throw ('snapshot copy mismatch: ' + $rel) }
            Write-Output ('snapshot ' + $rel + ' ' + $entry.sha256)
        } else {
            Write-Output ('snapshot ' + $rel + ' absent')
        }
        $snapFiles += $entry
        $dir = Split-Path -Parent $d
        while ($dir.Length -gt $Drop.Length -and -not (Test-Path -LiteralPath $dir)) {
            if ($created -notcontains $dir) { $created += $dir }
            $dir = Split-Path -Parent $dir
        }
    }
    [pscustomobject]@{
        schema = 2
        action = 'Install'
        created_at = (Get-Date).ToString('o')
        dropzone = $Drop
        files = $snapFiles
        created_dirs = $created
    } | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $Manifest -Encoding utf8
    foreach ($f in $Files) {
        $rel = $f[0]; $sha = $f[1]
        $s = Join-Path $Source $rel
        $d = Join-Path $Drop $rel
        EnsureDir (Split-Path -Parent $d)
        Copy-Item -LiteralPath $s -Destination $d -Force
        if ((HashOf $d) -ne $sha) { throw ('hash mismatch after copy: ' + $rel) }
        Write-Output ('installed ' + $rel); $n++
    }
    $existed = @($snapFiles | Where-Object { $_.existed }).Count
    Write-Output ('installed ' + $n + '/' + $Files.Count + '; snapshotted ' + $existed + ' existing target(s)')
}

if ($Action -eq 'Verify') {
    foreach ($f in $Files) {
        $rel = $f[0]; $sha = $f[1]
        $d = Join-Path $Drop $rel
        if ((Test-Path -LiteralPath $d) -and ((HashOf $d) -eq $sha)) { Write-Output ('ok ' + $rel); $n++ }
        else { Write-Output ('BAD ' + $rel); $bad++ }
    }
    Write-Output ('verified ' + $n + '/' + $Files.Count)
    if ($bad) { exit 1 }
}

if ($Action -eq 'Rollback') {
    if (-not (Test-Path -LiteralPath $Manifest)) {
        throw ('no snapshot manifest at ' + $Manifest + ' - nothing to restore')
    }
    $m = Get-Content -LiteralPath $Manifest -Raw | ConvertFrom-Json
    foreach ($e in $m.files) {
        $d = Join-Path $Drop $e.path
        if ($e.existed) {
            $bak = Join-Path (Join-Path $Snap 'files') $e.path
            if (-not (Test-Path -LiteralPath $bak)) { throw ('snapshot file missing: ' + $e.path) }
            EnsureDir (Split-Path -Parent $d)
            Copy-Item -LiteralPath $bak -Destination $d -Force
            if ((HashOf $d) -ne $e.sha256) { throw ('restored hash mismatch: ' + $e.path) }
            Write-Output ('restored ' + $e.path + ' ' + $e.sha256)
        } elseif (Test-Path -LiteralPath $d) {
            Remove-Item -LiteralPath $d -Force
            Write-Output ('removed ' + $e.path)
        } else {
            Write-Output ('already absent ' + $e.path)
        }
        $n++
    }
    foreach ($dir in ($m.created_dirs | Sort-Object Length -Descending)) {
        if ((Test-Path -LiteralPath $dir) -and -not (Get-ChildItem -LiteralPath $dir -Force)) {
            Remove-Item -LiteralPath $dir -Force
        }
    }
    Remove-Item -LiteralPath $Snap -Recurse -Force
    Write-Output ('rollback ' + $n + '/' + $Files.Count + ' target(s) match the pre-Install state; snapshot removed')
}
"""


def receipt_rows() -> list[tuple[str, str]]:
    d = json.load(open(RECEIPT, encoding="utf-8"))
    return [(f["path"], f["sha256"].upper()) for f in d["files"]]


def render() -> str:
    rows = receipt_rows()
    body = ",\n".join(f"    @('{rel.replace('/', chr(92))}', '{sha}')" for rel, sha in rows)
    text = HEADER.replace("__SIMROOT__", SIM_ROOT).replace("__ROWS__", body)
    return text.replace("\r\n", "\n")


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def tree(root: str) -> dict[str, str]:
    out = {}
    for dirpath, _d, files in os.walk(root):
        for name in files:
            p = os.path.join(dirpath, name)
            out[os.path.relpath(p, root).replace("\\", "/")] = sha256_file(p)
    return dict(sorted(out.items()))


def ps(action: str, gamedir: str, source: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [PWSH, "-NoProfile", "-File", OUT, "-Action", action, "-GameDir", gamedir,
         "-Source", source],
        capture_output=True, text=True)


def make_case(name: str, mode: str, rows: list[tuple[str, str]]) -> str:
    case = rf"E:\Modding\_dropzone_sim_rc2_case_{name}"
    shutil.rmtree(case, ignore_errors=True)
    drop = os.path.join(case, "dropzone")
    os.makedirs(drop)
    for rel, content in (("keep.txt", b"decoy-keep\n"),
                         ("editor/keep_me.bin", b"decoy-editor\n")):
        p = os.path.join(drop, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "wb").write(content)
    for rel, _sha in rows:
        if mode == "absent":
            continue
        d = os.path.join(drop, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(d), exist_ok=True)
        if mode == "same":
            shutil.copyfile(os.path.join(SRC, rel.replace("/", os.sep)), d)
        else:
            open(d, "wb").write(("stale:" + rel).encode())
    return case


def prove() -> tuple[list[str], dict]:
    failures: list[str] = []
    report: dict = {}
    rows = receipt_rows()

    # guard: a path outside the sim root, and a fake path under a real game root
    for label, path in (("outside-sim", r"E:\Modding\_not_a_sim_case"),
                        ("fake-game-root", r"D:\Games\Fake Just Cause 3")):
        r = ps("Install", path, SRC)
        ok = r.returncode == 2 and "REFUSED" in r.stdout and not os.path.exists(path)
        report[f"guard_{label}"] = {"exit": r.returncode, "refused": "REFUSED" in r.stdout,
                                    "created": os.path.exists(path), "out": r.stdout.strip()}
        if not ok:
            failures.append(f"guard {label} did not refuse cleanly (exit {r.returncode})")

    for name, mode in (("a", "differ"), ("b", "same"), ("c", "absent")):
        case = make_case(name, mode, rows)
        drop = os.path.join(case, "dropzone")
        pre = tree(drop)
        pre_hits = sum(1 for rel, sha in rows if pre.get(rel) == sha.lower())

        w = ps("WhatIf", case, SRC)
        i = ps("Install", case, SRC)
        post_install = tree(drop)
        v = ps("Verify", case, SRC)
        rb = ps("Rollback", case, SRC)
        post = tree(drop)

        snaps = i.stdout.count("snapshot ")
        if i.returncode != 0:
            failures.append(f"case {name}: Install exit {i.returncode}: {i.stdout[-400:]}{i.stderr[-400:]}")
        if v.returncode != 0 or "verified 9/9" not in v.stdout:
            failures.append(f"case {name}: Verify not 9/9")
        if rb.returncode != 0:
            failures.append(f"case {name}: Rollback exit {rb.returncode}: {rb.stdout[-400:]}{rb.stderr[-400:]}")
        if post != pre:
            diff = [k for k in set(pre) | set(post) if pre.get(k) != post.get(k)]
            failures.append(f"case {name}: tree differs after rollback: {sorted(diff)[:6]}")
        if mode == "same" and pre_hits != len(rows):
            failures.append(f"case {name}: pre-Install is not identical to the receipt ({pre_hits}/9)")
        if mode == "differ" and pre_hits != 0:
            failures.append(f"case {name}: pre-Install unexpectedly matches the receipt")
        if mode == "absent" and any(rel in pre for rel, _s in rows):
            failures.append(f"case {name}: payload present before Install")
        if snaps != len(rows):
            failures.append(f"case {name}: {snaps} snapshot lines, expected 9")
        if os.path.isdir(os.path.join(case, ".install_v2_snapshot")):
            failures.append(f"case {name}: snapshot directory survived Rollback")
        if any(k.endswith(".bm-RC2-backup") for k in post):
            failures.append(f"case {name}: backup files left behind")
        restored = rb.stdout.count("restored ")
        removed = rb.stdout.count("removed ")
        want_restored = 0 if mode == "absent" else len(rows)
        want_removed = len(rows) if mode == "absent" else 0
        if restored != want_restored or removed != want_removed:
            failures.append(f"case {name}: rollback restored {restored}/removed {removed}, "
                            f"expected {want_restored}/{want_removed}")

        summary = re.search(r"installed (\d+)/(\d+); snapshotted (\d+)", i.stdout)
        report[f"case_{name}"] = {
            "mode": mode, "pre_files": len(pre), "pre_matching_receipt": pre_hits,
            "snapshots": snaps,
            "installed": int(summary.group(1)) if summary else None,
            "snapshotted": int(summary.group(3)) if summary else None,
            "restored": restored, "removed": removed,
            "post_files": len(post), "identical_after_rollback": post == pre,
            "whatif_add": w.stdout.count("add ("), "whatif_same": w.stdout.count("same ("),
            "whatif_replace": w.stdout.count("replace ("),
        }
    return failures, report


def check() -> int:
    fails: list[str] = []
    if not os.path.exists(OUT):
        print(f"FAIL: {os.path.relpath(OUT, ROOT)} missing (run --write)")
        return 1
    fresh = render()
    if open(OUT, encoding="utf-8").read() != fresh:
        fails.append("install_v2.ps1 differs from a fresh generation")
    rows = receipt_rows()
    if len(rows) != 9:
        fails.append(f"receipt has {len(rows)} files, expected 9")
    for rel, sha in rows:
        if rel.replace("/", "\\") not in fresh or sha not in fresh:
            fails.append(f"embedded row missing: {rel}")
    v1 = open(os.path.join(ROOT, "Builds", "bm-RC2", "install.ps1"), encoding="utf-8-sig").read()
    if "Rollback091" not in v1:
        fails.append("install.ps1 changed - this card must not edit it")

    prove_fails, report = prove()
    fails.extend(prove_fails)

    print(f"rows {len(rows)} | cases {', '.join(k for k in report if k.startswith('case_'))}")
    for k, v in report.items():
        print(f"  {k}: {json.dumps(v, sort_keys=True)}")
    if fails:
        for f in fails:
            print(f"FAIL: {f}")
        print(f"CHECK_EXIT=1 ({len(fails)} failure(s))")
        return 1
    print("PASS: guard refuses both probe paths; in all three cases Install snapshots 9/9 and "
          "Rollback restores the pre-Install tree byte-for-byte (identical payload case included)")
    print("CHECK_EXIT=0")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.write == a.check:
        ap.error("pass exactly one of --write / --check")
    if a.check:
        return check()
    text = render()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(text)} chars, {len(receipt_rows())} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
