"""Write Builds/<tag>/install.ps1 for an .ee (+ optional .ee.toc) pair.

Every artifact is pinned by size + sha256; a build without a .toc REMOVES the dropzone .toc on
deploy, so older builds run exactly as they were tested.

Usage: python _make_installer.py <tag> "<desc>" [<rollback-tag> "<desc>"]...
"""
import hashlib
import os
import sys

ROOT = r"E:\Modding\JC3-Batmobile"
EE = "v0300_car_kensington_sportsmuscle_civilian_01.ee"
TARGET = (r"D:\Games\Just Cause 3\dropzone\editor\entities\jc_vehicles\01_land"
          r"\v0300_car_kensington_sportsmuscle\v0300_car_kensington_sportsmuscle_civilian_01.ee")


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest().upper()


def psq(s):
    """PowerShell single-quoted literal: a ' is written as ''."""
    return s.replace("'", "''")


def entry(tag, desc):
    d = os.path.join(ROOT, "Builds", tag)
    ee, toc = os.path.join(d, EE), os.path.join(d, EE + ".toc")
    s = (f"    '{tag}' = @{{ Path = '{ee}'\n"
         f"        Size = {os.path.getsize(ee)}; Sha = '{sha(ee)}'\n")
    if os.path.exists(toc):
        s += (f"        Toc = '{toc}'\n"
              f"        TocSize = {os.path.getsize(toc)}; TocSha = '{sha(toc)}'\n")
    return s + f"        Desc = '{psq(desc)}' }}\n"


TEMPLATE = r'''<#
    __TAG__ installer: __DESC__
    Deploys an .ee and (if the build has one) its .ee.toc as a pair; asserts size + sha256 of
    both. A build without a .toc REMOVES the dropzone .toc. Close the game first.
    Generated by Tools\scripts\_make_installer.py.
#>
[CmdletBinding()]
param(
    [ValidateSet(__ACTIONS__)]
    [string]$Action = 'Status'
)
$ErrorActionPreference = 'Stop'
$Target = '__TARGET__'
$TargetToc = $Target + '.toc'
$Artifacts = [ordered]@{
__ARTIFACTS__}
function Test-File($path, $size, $sha) {
    if (-not (Test-Path -LiteralPath $path)) { throw "artifact missing: $path" }
    $f = Get-Item -LiteralPath $path
    if ($f.Length -ne $size) { throw "size mismatch for $($f.Name): expected $size, found $($f.Length)" }
    $h = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
    if ($h -ne $sha) { throw "sha256 mismatch for $($f.Name): expected $sha, found $h" }
    Write-Host "verified $($f.Name): $($f.Length) B, sha256 $($h.Substring(0,16))..." -ForegroundColor DarkGray
}
function Deploy($name) {
    $a = $Artifacts[$name]
    Test-File $a.Path $a.Size $a.Sha
    if ($a.Toc) { Test-File $a.Toc $a.TocSize $a.TocSha }
    $dir = Split-Path -Parent $Target
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    Copy-Item -LiteralPath $a.Path -Destination $Target -Force
    if ($a.Toc) {
        Copy-Item -LiteralPath $a.Toc -Destination $TargetToc -Force
    } elseif (Test-Path -LiteralPath $TargetToc) {
        Remove-Item -LiteralPath $TargetToc -Force
        Write-Host 'removed dropzone .toc (vanilla .toc applies again)' -ForegroundColor DarkGray
    }
    Write-Host "deployed $($name): $($a.Desc)" -ForegroundColor Green
}
switch ($Action) {
__SWITCH__    'Status' {
        $eh = if (Test-Path -LiteralPath $Target) { (Get-FileHash -LiteralPath $Target).Hash } else { $null }
        $th = if (Test-Path -LiteralPath $TargetToc) { (Get-FileHash -LiteralPath $TargetToc).Hash } else { $null }
        Write-Host "dropzone .ee : $(if ($eh) { $eh } else { 'nothing deployed' })"
        Write-Host "dropzone .toc: $(if ($th) { $th } else { 'none (vanilla .toc applies)' })"
        foreach ($k in $Artifacts.Keys) {
            $a = $Artifacts[$k]
            if ($a.Sha -eq $eh -and (($a.Toc -and $a.TocSha -eq $th) -or (-not $a.Toc -and -not $th))) {
                Write-Host "  == $k (.ee and .toc both match)" -ForegroundColor Green
            }
        }
    }
}
'''


def main():
    args = sys.argv[1:]
    if len(args) < 2 or len(args) % 2:
        raise SystemExit(__doc__)
    pairs = list(zip(args[0::2], args[1::2]))
    tag, desc = pairs[0]
    actions = ["'Install'"] + [f"'Rollback{t.split('-')[-1]}'" for t, _ in pairs[1:]] + ["'Status'"]
    switch = f"    'Install'     {{ Deploy '{tag}' }}\n" + "".join(
        f"    'Rollback{t.split('-')[-1]}' {{ Deploy '{t}' }}\n" for t, _ in pairs[1:])
    out = (TEMPLATE.replace("__TAG__", tag).replace("__DESC__", desc.replace("#>", "# >"))
           .replace("__ACTIONS__", ", ".join(actions)).replace("__TARGET__", TARGET)
           .replace("__ARTIFACTS__", "".join(entry(t, d) for t, d in pairs))
           .replace("__SWITCH__", switch))
    path = os.path.join(ROOT, "Builds", tag, "install.ps1")
    open(path, "w", encoding="utf-8").write(out)
    print("wrote", path)


if __name__ == "__main__":
    main()
