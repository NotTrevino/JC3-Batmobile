"""grab_variants.py - G1-20: the four Batmobile variants, diffed (R11).

The card asks, per variant: mesh, LOD face counts, materials/textures that differ from
`Batmobile_V2`, socket differences, sim/weapon value differences. Every number in the answer is
counted here from `Research/BatmobileGrab/objects.jsonl` (the machine source), joined with
`MESHES.md` (geometry rows: verts, LOD faces, bones, materials, bounds) and `WEAPONS.md` (the
gadget/projectile class list and its field-comparison sentence).

Reads:
  * `objects.jsonl`  - every record, tag and name in the four vehicle packages,
  * `MESHES.md`      - per-mesh geometry rows (MESHES.md is itself generated by grab_meshes.py),
  * `WEAPONS.md`     - which classes are gadgets and which are projectiles, plus its
                       "0 of N field comparisons differ" sentence.

Writes:
    Research/BatmobileGrab/VARIANTS.md      generated page (every table + the D-5 inputs)

Usage:
    python Tools/scripts/grab_variants.py --write
    python Tools/scripts/grab_variants.py --check

`--check` re-derives everything, asserts the invariants the prose relies on (the set arithmetic
count = reference - missing + extra, one skin mesh per package, the four rigs' row equality,
0 differing sim tags, no `Default__` class default counted as a gadget) and compares the rendered
page with the file on disk.

Deliberately UNKNOWN, not guessed (R4):
  * why MK2/Funhouse serialise different export indices for the same reference targets - the
    reference *names* are identical, so the difference is export-table layout; what the exporter
    did is not recorded anywhere in the repo,
  * which of WEAPONS.md's two field-comparison totals ("332 fields" in its verdict line,
    "1065 field comparisons" in its section) is the count of fields - both say 0 differ.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

OUT = os.path.join(ROOT, "Research", "BatmobileGrab")
MD = os.path.join(OUT, "VARIANTS.md")
OBJ = os.path.join(OUT, "objects.jsonl")
MESHES = os.path.join(OUT, "MESHES.md")
WEAPONS = os.path.join(OUT, "WEAPONS.md")

# (key, package).  V2 is the reference every other variant is diffed against.
VARIANTS = (
    ("V2", "Playable_Batmobile_SF"),
    ("MK2", "Playable_BatmobileMK2_SF"),
    ("Joker", "Playable_BatmobileJoker_SF"),
    ("Funhouse", "Playable_BatmobileFunhouse_SF"),
)
REF = "V2"
SHARED_MESHES = ("Batmobile_V3_Destroyed", "Batmobile_V2_Fire", "Batwing_Carrier")
VEHICLE_CLASS = "RVehicleBatmobile"
SIM_CLASS = "RVehicleSimBatmobile"
MAT_CLASSES = ("Material", "MaterialInstanceConstant")
STD_RE = re.compile(r"_Std(_\d+)?_SF$")


def fmt(n):
    return "{:,}".format(n)


def load_objects():
    rows = []
    with open(OBJ, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def mesh_rows():
    """MESHES.md geometry rows, keyed (package, mesh)."""
    out = {}
    row_re = re.compile(
        r"^\| `([^`]+)` \| (\S+) \| (\d+) \| (\d+) \| (\d+) \| (\d+|—) \| (\d+) \| (\d+) \| (\S+ × \S+ × \S+) \|$")
    for line in open(MESHES, encoding="utf-8"):
        m = row_re.match(line.rstrip("\r\n"))
        if m:
            name, pkg, verts, l0, l1, l2, bones, mats, size = m.groups()
            out[(pkg, name)] = {
                "verts": int(verts), "lod0": int(l0), "lod1": int(l1),
                "lod2": None if l2 == "—" else int(l2),
                "bones": int(bones), "mats": int(mats), "size": size,
            }
    return out


def weapons_doc():
    """(gadget classes, projectile classes, comparison sentence, verdict sentence)."""
    gcls, pcls = set(), set()
    cmp_sentence = verdict = None
    lines = open(WEAPONS, encoding="utf-8").read().splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"\| (R\w+) \| (gadget|projectile) \|", line)
        if m:
            (gcls if m.group(2) == "gadget" else pcls).add(m.group(1))
        if cmp_sentence is None and re.search(r"0 of \d+ field comparisons differ", line):
            parts = [re.sub(r"^\*\*", "", line.strip())]
            for nxt in lines[i + 1:i + 4]:
                if not nxt.strip() or nxt.startswith(("|", "#")):
                    break
                parts.append(nxt.strip())
                if parts[-1].endswith("."):
                    break
            cmp_sentence = " ".join(parts).replace("**", "")
        if verdict is None and line.startswith("**Verdict.**"):
            verdict = line.strip()
    return gcls, pcls, cmp_sentence, verdict


def socket_name(rec):
    for t in rec["tags"] or []:
        if t.get("type") == "NameProperty":
            return t.get("value")
    return None


def tag_sig(t):
    """What a tag carries that a variant could change: type, index, value / floats, and for a
    struct the nested properties (a `VehicleLights` row changes when its inner reference does)."""
    sig = (t.get("type"), t.get("array_index"), repr(t.get("value")),
           t.get("count"), tuple(round(x, 6) for x in (t.get("floats") or [])))
    if t.get("props"):
        sig += (tuple((p.get("name"), p.get("type"), repr(p.get("value")), p.get("ref"))
                      for p in t["props"]),)
    return sig


def target_of(ref):
    """`Package.Object` -> `Object`, so a package prefix does not read as a retarget."""
    return (ref or "").split(".", 1)[1] if "." in (ref or "") else (ref or "")


def rig_rows(veh):
    """[{bone, type, material}] in serialisation order, from the `VehicleLights` structs."""
    rows = []
    for st in [t for t in veh["tags"] if t.get("name") == "VehicleLights"]:
        bone = typ = mat = None
        for pp in st.get("props") or []:
            if pp.get("name") == "Type":
                typ = pp.get("value")
            elif pp.get("name") == "MaterialType":
                mat = pp.get("value")
            elif pp.get("type") == "NameProperty":
                bone = pp.get("value")
        rows.append({"bone": bone, "type": typ, "material": mat})
    return rows


def build():
    rows = load_objects()
    meshes = mesh_rows()
    gcls, pcls, cmp_sentence, verdict = weapons_doc()

    by_pkg = {}
    for r in rows:
        by_pkg.setdefault(r.get("package"), []).append(r)

    doc = {"variants": {}, "shared": [], "std": [], "weapons": {
        "gcls": sorted(gcls), "pcls": sorted(pcls),
        "cmp": cmp_sentence, "verdict": verdict}}

    for key, pkg in VARIANTS:
        rs = by_pkg.get(pkg, [])
        veh = [r for r in rs if r["class"] == VEHICLE_CLASS]
        sims = [r for r in rs if r["class"] == SIM_CLASS]
        skins = sorted({r["name"] for r in rs if r["class"] == "SkeletalMesh"
                        and r["name"] not in SHARED_MESHES})
        sockets = sorted(socket_name(r) for r in rs if r["class"] == "SkeletalMeshSocket")
        mats = sorted({r["name"] for r in rs if r["class"] in MAT_CLASSES})
        tex = sorted({r["name"] for r in rs if r["class"] == "Texture2D"})
        v = {
            "key": key, "package": pkg,
            "records": len(rs),
            "vehicle": veh[0] if len(veh) == 1 else None,
            "sim": sims[0] if len(sims) == 1 else None,
            "skins": skins,
            "sockets": sockets,
            "materials": mats,
            "textures": tex,
            "gadgets": sorted(r["name"] for r in rs if r["class"] in gcls),
            "gadget_defaults": sorted(r["name"] for r in rs if r["class"] in gcls
                                      and (r["name"] or "").startswith("Default__")),
            "projectiles": sorted(r["name"] for r in rs if r["class"] in pcls),
            "threat": sorted((r["class"], r["name"]) for r in rs
                             if r["class"] and "Threat" in r["class"]),
        }
        v["gadgets"] = [g for g in v["gadgets"] if not g.startswith("Default__")]
        v["sim_size"] = v["sim"]["size"] if v["sim"] else None
        v["sim_tags"] = len(v["sim"]["tags"]) if v["sim"] else None
        v["rig"] = rig_rows(v["vehicle"]) if v["vehicle"] else []
        v["rig_mat"] = sum(1 for r in v["rig"] if r["material"])
        v["named"] = [t for t in (v["vehicle"]["tags"] if v["vehicle"] else []) if t.get("name")]
        v["props"] = [t for t in v["named"] if t.get("name") != "VehicleLights"]
        v["mesh"] = []
        for name in skins:
            rec = [r for r in rs if r["class"] == "SkeletalMesh" and r["name"] == name][0]
            g = meshes.get((pkg, name))
            if g is None:
                raise SystemExit("MESHES.md has no row for %s / %s" % (pkg, name))
            v["mesh"].append({"name": name, "export": rec["size"], **g})
        doc["variants"][key] = v

    ref = doc["variants"][REF]

    # set differences against the reference
    for key in doc["variants"]:
        v = doc["variants"][key]
        if key == REF:
            continue
        for kind_ref, kind_v in (("materials", "extra_materials"), ("textures", "extra_textures")):
            a, b = set(ref[kind_ref]), set(v[kind_ref])
            v[kind_v] = sorted(b - a)
            v["missing_" + kind_v.split("_", 1)[1]] = sorted(a - b)

    # vehicle-object tag diff against the reference (same offset, different value)
    a_tags = {t["offset"]: t for t in ref["vehicle"]["tags"]}
    named_offsets = {t["offset"] for t in ref["props"]}
    for key in doc["variants"]:
        v = doc["variants"][key]
        if key == REF:
            continue
        b_tags = {t["offset"]: t for t in v["vehicle"]["tags"]}
        common = sorted(set(a_tags) & set(b_tags))
        diff = [o for o in common if tag_sig(a_tags[o]) != tag_sig(b_tags[o])]
        structs = [o for o in diff if a_tags[o].get("type") == "StructProperty"]
        rig_structs = [o for o in structs if a_tags[o].get("name") == "VehicleLights"]
        other_structs = [o for o in structs if o not in rig_structs]
        refs = [o for o in diff if a_tags[o].get("type") == "ObjectNCRProperty"]
        floats = [o for o in diff if a_tags[o].get("type") == "FloatProperty"]
        other = [o for o in diff if o not in structs and o not in refs and o not in floats]
        v["diff"] = {
            "common": len(common),
            "total": len(diff),
            "structs": len(structs),
            "rig_structs": len(rig_structs),
            "other_structs": sorted({a_tags[o].get("name") for o in other_structs}),
            "refs": [{"offset": o, "ref": a_tags[o].get("ref"),
                      "a": a_tags[o].get("value"), "b": b_tags[o].get("value"),
                      "b_ref": b_tags[o].get("ref"),
                      "same_target": (target_of(a_tags[o].get("ref"))
                                      == target_of(b_tags[o].get("ref")))}
                     for o in refs],
            "floats": [{"offset": o, "a": round(a_tags[o].get("value"), 4),
                        "b": round(b_tags[o].get("value"), 4)} for o in floats],
            "other": sorted(other),
            "v2_only": sorted(set(a_tags) - set(b_tags)),
            "v_only": sorted(set(b_tags) - set(a_tags)),
        }
        # named properties present in one object and not the other
        v["props_missing"] = [t for t in ref["props"] if t["name"] not in {x["name"] for x in v["props"]}]
        v["props_extra"] = [t for t in v["props"] if t["name"] not in {x["name"] for x in ref["props"]}]

    # sim: tag-by-tag across all four
    sim_ref = ref["sim"]
    sim_diff = []
    for key in doc["variants"]:
        v = doc["variants"][key]
        if key == REF:
            continue
        sig_a = [tag_sig(t) for t in sim_ref["tags"]]
        sig_b = [tag_sig(t) for t in v["sim"]["tags"]]
        n = sum(1 for x, y in zip(sig_a, sig_b) if x != y)
        sim_diff.append((key, n, len(sig_a), len(sig_b)))
    doc["sim_diff"] = sim_diff

    # shared side-meshes: which packages carry them
    for name in SHARED_MESHES:
        pkgs = []
        for key, pkg in VARIANTS:
            rec = [r for r in by_pkg.get(pkg, []) if r["class"] == "SkeletalMesh" and r["name"] == name]
            if rec:
                g = meshes.get((pkg, name), {})
                pkgs.append({"key": key, "export": rec[0]["size"], **g})
        doc["shared"].append({"name": name, "in": pkgs})
    doc["rbatwing"] = [(r["name"], r["size"]) for r in by_pkg.get("Playable_BatmobileJoker_SF", [])
                       if r["class"] == "RBatwing"]

    # the 11 `_Std_*` side packages
    std = []
    for pkg in sorted(by_pkg):
        if pkg and STD_RE.search(pkg):
            rs = by_pkg[pkg]
            extra = sorted({r["name"] for r in rs if r["class"] == "Material"})
            std.append({"package": pkg, "records": len(rs), "materials": extra})
    doc["std"] = std
    return doc


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return out


def render(doc):
    V = doc["variants"]
    ref = V[REF]
    L = []
    A = L.append
    A("# Batmobile skins and variants (G1-20)")
    A("")
    A("Generated by `Tools/scripts/grab_variants.py` from `Research/BatmobileGrab/objects.jsonl`")
    A("(every record, tag and name in the four vehicle packages), joined with `MESHES.md`")
    A("(geometry rows: verts, LOD faces, bones, materials, bounds) and `WEAPONS.md` (the")
    A("gadget/projectile class list and its field-comparison sentence). `--check` re-derives every")
    A("number below and compares this page with the render.")
    A("")
    A("A \"variant\" here is one of the four **full vehicle packages**; `Batmobile_V2` in")
    A("`Playable_Batmobile_SF` is the reference every other variant is diffed against.")
    A("")
    rows = []
    for key, pkg in VARIANTS:
        v = V[key]
        rows.append([("**%s**%s" % (key, " (reference)" if key == REF else "")), "`%s`" % pkg,
                     "`%s` (%s B)" % (v["vehicle"]["name"], fmt(v["vehicle"]["size"])),
                     fmt(v["records"]), "`%s`" % v["vehicle"]["outer"]])
    L += table(["variant", "package", "vehicle object", "records", "outer"], rows)
    A("")
    A("The four skin meshes: " + "; ".join(
        "**%s** `%s`" % (V[k]["key"], V[k]["mesh"][0]["name"]) for k, _ in VARIANTS) + ".")
    A("")
    A("%d `_Std_*` packages accompany them:" % len(doc["std"]))
    A("")
    rows = []
    for s in doc["std"]:
        rows.append(["`%s`" % s["package"], fmt(s["records"]),
                     ", ".join("`%s`" % m for m in s["materials"]) or "—"])
    L += table(["package", "records", "its own material"], rows)
    A("")
    A("Every `_Std_*` package carries four records (`ObjectReferencer`, two `Package`, one")
    A("`RAddContentBatmobileMesh`) except the one that also carries a material — that material is")
    A("the upgrade-stage skin, not a vehicle.")
    A("")

    # 1. mesh
    A("## 1. Mesh")
    A("")
    A("Geometry from `MESHES.md`; the export size is the `SkeletalMesh` record size in")
    A("`objects.jsonl`. Bounds are the raw PSKX values (the PSKX is in cm — see `TYRES.md`, which")
    A("measures the same file at ×0.01 m); `MESHES.md` heads that column `(m)`, which the values")
    A("do not support.")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        for m in v["mesh"]:
            rows.append([key, "`%s`" % m["name"], fmt(m["verts"]), fmt(m["lod0"]),
                         fmt(m["lod1"]), fmt(m["lod2"]) if m["lod2"] else "—",
                         m["bones"], m["mats"], m["size"], fmt(m["export"])])
    L += table(["variant", "mesh", "verts", "LOD0", "LOD1", "LOD2", "bones", "materials",
                "bounds (cm)", "export (B)"], rows)
    A("")
    ref0 = ref["mesh"][0]
    notes = []
    for key, _ in VARIANTS[1:]:
        m = V[key]["mesh"][0]
        notes.append("%s LOD0 %s faces (%+.2f%%)" % (key, fmt(m["lod0"]),
                                                     (m["lod0"] / ref0["lod0"] - 1) * 100))
    A("V2 LOD0 is %s faces; %s." % (fmt(ref0["lod0"]), "; ".join(notes)))
    joker_fh = V["Joker"]["mesh"][0]["export"] == V["Funhouse"]["mesh"][0]["export"]
    A("The Joker and Funhouse skins are %s." % (
        "the **same export** (%s B each)" % fmt(V["Joker"]["mesh"][0]["export"]) if joker_fh
        else "different exports (**not** the same mesh bytes)"))
    A("")
    A("Shared side-meshes:")
    A("")
    rows = []
    for s in doc["shared"]:
        ins = [x["key"] for x in s["in"]]
        rows.append(["`%s`" % s["name"],
                     "%s / %s" % (fmt(s["in"][0]["lod0"]), fmt(s["in"][0]["lod1"])) if s["in"] else "—",
                     s["in"][0]["bones"] if s["in"] else "—",
                     s["in"][0]["mats"] if s["in"] else "—",
                     fmt(s["in"][0]["export"]) if s["in"] else "—",
                     ", ".join(ins) or "—"])
    L += table(["mesh", "LOD0 / LOD1", "bones", "materials", "export (B)", "in"], rows)
    A("")
    if doc["rbatwing"]:
        A("The Joker package also ships " + ", ".join("`%s` (%s B)" % (n, fmt(s))
                                                      for n, s in doc["rbatwing"]) + ".")
        A("")

    # 2. sockets
    A("## 2. Sockets")
    A("")
    A("Counted from the `SkeletalMeshSocket` records (socket name = the record's `NameProperty`).")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        rows.append([key, fmt(len(v["sockets"])), fmt(len(set(v["sockets"])))])
    L += table(["variant", "sockets", "distinct names"], rows)
    A("")
    ref_s = set(ref["sockets"])
    for key, _ in VARIANTS[1:]:
        v = V[key]
        s = set(v["sockets"])
        A("**%s** — %d; only here: %s; missing vs V2 (%d): %s." % (
            key, len(v["sockets"]),
            ", ".join("`%s`" % x for x in sorted(s - ref_s)) or "none",
            len(ref_s - s),
            ", ".join("`%s`" % x for x in sorted(ref_s - s)) or "none"))
        A("")

    # 3. materials
    A("## 3. Materials (`Material` + `MaterialInstanceConstant`)")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        rows.append([key, fmt(len(v["materials"])),
                     "—" if key == REF else fmt(len(v["extra_materials"])),
                     "—" if key == REF else fmt(len(v["missing_materials"]))])
    L += table(["variant", "count", "extra vs V2", "missing vs V2"], rows)
    A("")
    A("Each row closes: `count = 78 - missing + extra`.")
    A("")
    if "Funhouse" in V and "Joker" in V:
        fx, jx = set(V["Funhouse"]["extra_materials"]), set(V["Joker"]["extra_materials"])
        A("Funhouse and Joker ship the same skin mesh, so their sets nest: Funhouse's %d extra "
          "materials are %s Joker's %d, and it lacks %s." % (
              len(fx), "all of" if fx <= jx else "not all of", len(jx),
              ", ".join("`%s`" % x for x in sorted(jx - fx)) or "none of them"))
        A("")
    for key, _ in VARIANTS[1:]:
        v = V[key]
        A("**%s only (%d):** %s." % (key, len(v["extra_materials"]),
                                     ", ".join("`%s`" % x for x in v["extra_materials"]) or "none"))
        A("")
        A("**In V2, not in %s (%d):** %s." % (key, len(v["missing_materials"]),
                                              ", ".join("`%s`" % x for x in v["missing_materials"]) or "none"))
        A("")

    # 4. textures
    A("## 4. Textures (`Texture2D`)")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        rows.append([key, fmt(len(v["textures"])),
                     "—" if key == REF else fmt(len(v["extra_textures"])),
                     "—" if key == REF else fmt(len(v["missing_textures"]))])
    L += table(["variant", "count", "extra vs V2", "missing vs V2"], rows)
    A("")
    A("Each row closes: `count = 92 - missing + extra`.")
    A("")
    fx, jx = set(V["Funhouse"]["extra_textures"]), set(V["Joker"]["extra_textures"])
    A("Funhouse's %d extra textures are %s Joker's %d; it lacks %s." % (
        len(fx), "all of" if fx <= jx else "not all of", len(jx),
        ", ".join("`%s`" % x for x in sorted(jx - fx)) or "none of them"))
    A("")
    for key, _ in VARIANTS[1:]:
        v = V[key]
        A("**%s only (%d):** %s." % (key, len(v["extra_textures"]),
                                     ", ".join("`%s`" % x for x in v["extra_textures"]) or "none"))
        A("")
        A("**In V2, not in %s (%d):** %s." % (key, len(v["missing_textures"]),
                                              ", ".join("`%s`" % x for x in v["missing_textures"]) or "none"))
        A("")

    # 5. simulation
    A("## 5. Simulation")
    A("")
    A("`RVehicleSimBatmobile` in every package, compared tag by tag (type, value, array contents):")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        n = 0
        for k2, d, na, nb in doc["sim_diff"]:
            if k2 == key:
                n = d
        rows.append([key, "`%s`" % v["sim"]["name"], fmt(v["sim_size"]), v["sim_tags"],
                     "—" if key == REF else "%d differing tags" % n])
    L += table(["variant", "object", "size (B)", "tags", "vs V2"], rows)
    A("")
    A("The same object, byte for byte: every variant carries the same wheels, mass, torque curves")
    A("and suspension. No skin changes handling.")
    A("")

    # 6. vehicle object
    A("## 6. Vehicle object (`RVehicleBatmobile`)")
    A("")
    A("`named tags` counts the tags that carry a property name (`VehicleLights` included once per")
    A("rig row); the rest are unnamed references and scalars.")
    A("")
    rows = []
    for key, _ in VARIANTS:
        v = V[key]
        rows.append([key, fmt(v["vehicle"]["size"]), fmt(len(v["named"])), len(v["props"]),
                     len(v["rig"]), v["rig_mat"]])
    L += table(["variant", "size (B)", "named tags", "named properties", "light-rig rows",
                "rows binding a `MaterialType`"], rows)
    A("")
    for key, _ in VARIANTS[1:]:
        v = V[key]
        if v["props_missing"] or v["props_extra"]:
            A("**%s property diff vs V2.**" % key)
            A("")
            rows = []
            for t in v["props_missing"]:
                rows.append([t["name"], "`%s`" % t["type"], "0x%x" % t["offset"],
                             "`%s`" % str(t.get("value")), "absent"])
            for t in v["props_extra"]:
                rows.append([t["name"], "`%s`" % t["type"], "0x%x" % t["offset"],
                             "absent", "`%s`" % str(t.get("value"))])
            L += table(["property", "type", "offset", "V2", key], rows)
