def invariants(doc):
    V = doc["variants"]
    ref = V[REF]
    bad = []
    if len(V) != 4:
        bad.append("expected 4 variants, got %d" % len(V))
    base = len(ref["materials"])
    for key, _ in VARIANTS:
        v = V[key]
        if v["vehicle"] is None:
            bad.append("%s: expected exactly one %s" % (key, VEHICLE_CLASS))
            continue
        if len(v["mesh"]) != 1:
            bad.append("%s: expected exactly one skin mesh, got %d (%s)" %
                       (key, len(v["mesh"]), v["skins"]))
        if key != REF:
            n = base - len(v["missing_materials"]) + len(v["extra_materials"])
            if n != len(v["materials"]):
                bad.append("%s: materials %d - %d + %d = %d != %d" % (
                    key, base, len(v["missing_materials"]), len(v["extra_materials"]),
                    n, len(v["materials"])))
            n = len(ref["textures"]) - len(v["missing_textures"]) + len(v["extra_textures"])
            if n != len(v["textures"]):
                bad.append("%s: textures %d - %d + %d = %d != %d" % (
                    key, len(ref["textures"]), len(v["missing_textures"]),
                    len(v["extra_textures"]), n, len(v["textures"])))
            if not v["diff"]["total"]:
                bad.append("%s: vehicle object shows no tag difference vs V2" % key)
            if v["diff"]["other"]:
                bad.append("%s: differing tags of an unclassified type: %s" % (
                    key, ", ".join("0x%X" % o for o in v["diff"]["other"])))
            for f in v["diff"]["refs"]:
                if not f["ref"]:
                    bad.append("%s: differing reference 0x%X has no target name" % (key, f["offset"]))
        if key in ("MK2", "Funhouse") and v["diff"]["floats"]:
            bad.append("%s: %d unnamed floats differ (only Joker has a different float layout)" %
                       (key, len(v["diff"]["floats"])))
        if len(set(v["sockets"])) != len(v["sockets"]):
            bad.append("%s: duplicate socket names" % key)
        for g in v["gadgets"]:
            if g.startswith("Default__"):
                bad.append("%s: class default %s counted as a gadget" % (key, g))
        if any("Threat" in (c or "") for c, _ in v["threat"]):
            if any("Threat" in g for g in v["gadgets"]):
                bad.append("%s: a threat component is counted as a gadget" % key)
    for key, n, na, nb in doc["sim_diff"]:
        if n or na != nb:
            bad.append("%s: sim tags differ (%d of %d/%d)" % (key, n, na, nb))
    if len(ref["rig"]) != 28 or ref["rig_mat"] != 18:
        bad.append("reference rig: %d rows, %d with MaterialType (expected 28 / 18)" %
                   (len(ref["rig"]), ref["rig_mat"]))
    for key in ("MK2", "Funhouse"):
        if V[key]["rig"] != ref["rig"]:
            bad.append("%s: light rig is not identical to V2" % key)
    if V["Joker"]["rig_mat"]:
        bad.append("Joker binds a MaterialType on %d rows (expected 0)" % V["Joker"]["rig_mat"])
    if V["Joker"]["mesh"][0]["export"] != V["Funhouse"]["mesh"][0]["export"]:
        bad.append("Joker/Funhouse no longer ship the same skin export")
    if not doc["std"] or any(s["records"] != 4 for s in doc["std"] if "Std_6" not in s["package"]):
        bad.append("a _Std_* package no longer carries 4 records")
    return bad


