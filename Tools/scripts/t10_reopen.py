# A foreign `out` row (one another card wrote after this one) must cite a proof: an existing
# repo path in backticks, or a real §7 card id.  Substring magic ("\\.md" anywhere, a dangling
# "G2-99") is not a proof - the review refuted exactly that.
PATH_RE = re.compile(r"`([^`]+\.(?:md|json|jsonl|py|ctunec|ps1|txt))`")
CARD_ID_RE = re.compile(r"\b([TGB](?:\d+)?-\d+)\b")

CARD_RE = re.compile(r"^####\s+([TGB](?:\d+)?-\d+)\s+·", re.M)
LEDGER_ROW_RE = re.compile(r"^\|\s*(T-[A-Z]{1,3}\d+)\s*\|")


def norm(ev: tuple) -> dict:
    """(kind, file, needle|anchor, note), (kind, file, anchor, must_not, note), or
    (kind, file, anchor, must_not, note, allow) -> dict."""
    kind, path = ev[0], ev[1]
    if kind == "needle":
        return {"kind": kind, "file": path, "need": ev[2], "anchor": "",
                "must_not": [], "allow": {}, "note": ev[3]}
    if kind == "absent":
        return {"kind": kind, "file": path, "need": "", "anchor": ev[2],
                "must_not": list(ev[3]), "allow": {}, "note": ev[4]}
    if kind == "hud":
        return {"kind": kind, "file": "", "need": "", "anchor": "",
                "must_not": list(ev[3]), "allow": dict(ev[5]) if len(ev) > 5 else {},
                "note": ev[4]}
    if kind == "exists":
        return {"kind": kind, "file": path, "need": "", "anchor": "",
                "must_not": [], "allow": {}, "note": ev[3]}
    raise SystemExit(f"unknown evidence kind {kind!r}")


def rel(p: str) -> str:
    """Repo-relative when the path is inside the repo, absolute (forward slashes) otherwise."""
    p = os.path.abspath(p)
    try:
        if os.path.commonpath([p, ROOT]) == ROOT:
            return os.path.relpath(p, ROOT).replace("\\", "/")
    except ValueError:            # different drives on Windows
        pass
    return p.replace("\\", "/")


def read(path: str) -> str:
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def hud_text() -> tuple[str, int]:
    """The decompiled ui/hud.gfx scripts, concatenated and lowercased."""
    scripts: list[str] = []
    for base, _dirs, files in os.walk(HUD_DEC):
        for name in files:
            if name.endswith(".as"):
                scripts.append(os.path.join(base, name))
    return "\n".join(read(p) for p in scripts).lower(), len(scripts)


def prove(ev: dict, hud: tuple[str, int]) -> dict:
    """Check one evidence triple and return {ok, detail}."""
    kind = ev["kind"]
    if kind == "needle":
        path = os.path.join(ROOT, ev["file"])
        if not os.path.exists(path):
            return {"ok": False, "detail": f"missing file {ev['file']}"}
        text = read(path)
        at = text.find(ev["need"])
        if at < 0:
            return {"ok": False, "detail": f"{ev['file']} does not contain {ev['need']!r}"}
        line = text[text.rfind("\n", 0, at) + 1: text.find("\n", at)]
        return {"ok": True, "detail": f"{ev['file']}: {line.strip()[:180]}"}
    if kind == "absent":
        path = os.path.join(ROOT, ev["file"])
        if not os.path.exists(path):
            return {"ok": False, "detail": f"missing file {ev['file']}"}
        text = read(path)
        if ev["anchor"] not in text:
            return {"ok": False,
                    "detail": f"{ev['file']} does not contain the anchor {ev['anchor']!r}: "
                              f"the census surface was not read"}
        low = text.lower()
        hits = [w for w in ev["must_not"] if w in low]
        if hits:
            return {"ok": False,
                    "detail": f"{ev['file']} names {', '.join(hits)}: the absence is refuted"}
        return {"ok": True,
                "detail": f"{ev['file']}: anchor {ev['anchor']!r} present, "
                          f"0 hits of {', '.join(ev['must_not'])}"}
    if kind == "hud":
        text, n = hud
        if n < 1:
            return {"ok": False, "detail": f"{rel(HUD_DEC)}: no .as scripts found"}
        unexplained: list[str] = []
        explained: list[str] = []
        for w in ev["must_not"]:
            total = text.count(w)
            if not total:
                continue
            allowed = sum(len(re.findall(p, text)) for p in ev.get("allow", {}).get(w, []))
            if total > allowed:
                unexplained.append(f"{w} ({total - allowed} of {total})")
            else:
                explained.append(f"{w} {total} all in the allow-list")
        if unexplained:
            return {"ok": False,
                    "detail": f"{rel(HUD_DEC)}: ui/hud.gfx names {', '.join(unexplained)}"}
        tail = f"; explained: {', '.join(explained)}" if explained else ""
        return {"ok": True,
                "detail": f"{rel(HUD_DEC)}: {n} scripts read, 0 unexplained hits of "
                          f"{', '.join(ev['must_not'])}{tail}"}
    if kind == "exists":
        path = os.path.join(ROOT, ev["file"])
        if not os.path.exists(path):
            return {"ok": False, "detail": f"missing file {ev['file']}"}
        size = os.path.getsize(path)
        if size < 1:
            return {"ok": False, "detail": f"empty file {ev['file']}"}
        return {"ok": True, "detail": f"{ev['file']}: exists, {size:,} B"}
    raise SystemExit(f"unknown evidence kind {kind!r}")


def backlog_cards() -> set[str]:
    return set(CARD_RE.findall(read(BACKLOG)))


def backlog_decisions() -> dict[str, bool]:
    """§11 decision id -> resolved flag, read from the register itself."""
    text = read(BACKLOG)
    at = text.find("## 11. Decision register")
    end = text.find("## 12. Tracker", at)
    out: dict[str, bool] = {}
    for line in text[at:end].splitlines():
        m = re.match(r"^\|\s*(D-\d+)\s*\|", line)
        if m:
            out[m.group(1)] = "resolved" in line.lower()
    return out


def t6_rows() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for line in read(T6).splitlines():
        if not line.startswith("| T-"):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) < 8:
            continue
        proposed = c[5]
        if "**superseded" in proposed:
            dispo = "superseded"
        elif "**out**" in proposed:
            dispo = "out"
        elif "**blocked" in proposed:
            dispo = "blocked"
        else:
            dispo = "other"
        out[c[0]] = {"dispo": dispo, "proposed": proposed,
                     "successors": sorted(re.findall(r"\bT-\d+\b", proposed))}
    return out


def ledger_rows() -> dict[str, dict]:
    rows = {}
    for line in open(LEDGER, encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            rows[r["id"]] = r
    return rows


def cited_proof(why: str, cards: set[str]) -> str:
    """The proof another card's `out` row cites: an existing repo path, or a real card id."""
    for m in PATH_RE.finditer(why):
        if os.path.exists(os.path.join(ROOT, m.group(1))):
            return m.group(1)
    for m in CARD_ID_RE.finditer(why):
        if m.group(1) in cards:
            return m.group(1)
    return ""


def derive() -> tuple[dict, dict]:
    f = facts()
    hud = hud_text()
    cards = backlog_cards()
    dec_state = backlog_decisions()
    led = ledger_rows()
    t6 = t6_rows()
    specs = rows_spec(f)
    rows, problems = [], []
    for spec in specs:
        ev_out = []
        for raw in spec["evidence"]:
            ev = norm(raw)
            d = {"kind": ev["kind"], "file": ev["file"] or rel(HUD_DEC),
                 "need": ev["need"], "anchor": ev["anchor"],
                 "must_not": ev["must_not"], "allow": ev["allow"], "why": ev["note"]}
            d.update(prove(ev, hud))
            ev_out.append(d)
            if not d["ok"]:
                problems.append(f"{spec['id']}: {d['detail']}")
        # the successor rows must be real cards, and their §11 gates must be in the register
        for s in spec["successors"]:
            if s not in cards:
                problems.append(f"{spec['id']}: successor {s} is not a card in §7")
        for d_id in spec["decisions"]:
            if d_id not in dec_state:
                problems.append(f"{spec['id']}: decision {d_id} is not in the §11 register")
        # the disposition the row actually carries, from its own file
        if spec["where"] == "ledger":
            if spec["id"] not in led:
                problems.append(f"{spec['id']}: not in T_ROWS.jsonl")
                actual = "(absent)"
            else:
                actual = led[spec["id"]]["dispo"]
                if led[spec["id"]].get("why", "") != spec["why"]:
                    problems.append(f"{spec['id']}: ledger `why` differs from the T-10 table "
                                    f"(run `t_rows.py build` after updating DISPO)")
                sup = led[spec["id"]].get("superseded_by", [])
                if spec["now"] == "superseded" and sup != spec["successors"]:
                    problems.append(f"{spec['id']}: ledger writes superseded_by {sup}, "
                                    f"the table says {spec['successors']}")
        else:
            if spec["id"] not in t6:
                problems.append(f"{spec['id']}: not in T6_HUD_CAMERA.md")
                actual = "(absent)"
            else:
                actual = t6[spec["id"]]["dispo"]
                must = spec.get("cell_must", "")
                if must and must not in t6[spec["id"]]["proposed"]:
                    problems.append(f"{spec['id']}: the T6 cell does not name {must!r}")
        if actual != spec["now"]:
            problems.append(f"{spec['id']}: {spec['where']} says {actual!r}, "
                            f"the T-10 table says {spec['now']!r}")
        rows.append({
            "id": spec["id"], "doc": spec["doc"], "where": spec["where"],
            "was": spec["was"], "now": spec["now"], "actual": actual,
            "successors": spec["successors"],
            "decisions": [{"id": d, "resolved": dec_state.get(d, False)}
                          for d in spec["decisions"]],
            "feature": spec["feature"], "evidence": ev_out,
            "why": spec["why"], "split": spec["split"],
        })
    # every `out` row that exists must carry a proof (the card's Done check).  A row this
    # table owns is proven by the evidence reads above; a row another card wrote later (the
    # ledger is shared) must at least cite its proof in `why`/its T6 cell.
    out_now = {r["id"] for r in rows if r["now"] == "out"}
    out_found = ({k for k, v in led.items() if v["dispo"] == "out"} |
                 {k for k, v in t6.items() if v["dispo"] == "out"})
    proven = 0
    foreign_cited = 0
    foreign_unproven: list[str] = []
    for rid in sorted(out_found - out_now):
        why = (led.get(rid, {}).get("why", "") or t6.get(rid, {}).get("proposed", ""))
        if cited_proof(why, cards):
            foreign_cited += 1
        else:
            # another card's row, written after this one: reported, not failed.  It is not
            # T-10's row to prove and the card that owns it may still be mid-session.  The
            # census is printed live and deliberately NOT stored: a shared ledger would rot
            # this card's artifact every time another card adds an `out` row.
            foreign_unproven.append(rid)
    for rid in sorted(out_now - out_found):
        problems.append(f"{rid}: the table keeps it `out` but the files do not")
    for r in rows:
        if r["now"] == "out" and all(e["ok"] for e in r["evidence"]):
            proven += 1
    # rows the table names but which do not exist at all
    for spec in specs:
        if spec["id"] not in led and spec["id"] not in t6:
            problems.append(f"{spec['id']}: not a row in either file")
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["now"]] = counts.get(r["now"], 0) + 1
    open_dec = sorted({d["id"] for r in rows for d in r["decisions"] if not d["resolved"]})
    payload = {
        "card": "T-10",
        "generated_by": "Tools/scripts/t10_reopen.py --write",
        "summary": {
            "rows": len(rows),
            "superseded": counts.get("superseded", 0),
            "out": counts.get("out", 0),
            "blocked": counts.get("blocked", 0),
            "successors": sorted({s for r in rows for s in r["successors"]}),
            "decisions_open": open_dec,
            "evidence_files": sorted({e["file"] for r in rows for e in r["evidence"]}),
            "out_rows_with_proof": proven,
            "hud_scripts": hud[1],
            "vocab_types": f["vocab_types"], "vocab_paths": f["vocab_paths"],
            "census_classes": f["census_classes"],
            "problems": len(problems),
        },
        "rows": rows,
        "problems": problems,
    }
    census = {"cited": foreign_cited, "unproven": foreign_unproven,
              "total": len(out_found - out_now)}
    return payload, census


def markdown(p: dict) -> str:
    s = p["summary"]
    L = [
        "# T-10 — re-opening the `out` rows against the G2 evidence",
        "",
        "Generated by `Tools/scripts/t10_reopen.py --write`; `--check` re-reads every evidence",
        "file and re-compares the table with `T_ROWS.jsonl` and `T6_HUD_CAMERA.md`.",
        "",
        "The card (`GRAB_BACKLOG.md` §7) re-decides every row that said `out` — \"no JC3 expression",
        "exists\" — now that phase G2 has closed the carrier question. A row with a carrier is",
        "**superseded** by the phase-T card that will write it; a row without one keeps `out` and",
        "names the G2 file that proves the absence.",
        "",
        "| item | value |",
        "|---|---|",
        f"| rows re-decided | **{s['rows']}** (the card's 15 `out` rows + `T-HUD5`, which its "
        "expected-outcome line names) |",
        f"| now `superseded` (a carrier exists) | **{s['superseded']}** |",
        f"| still `out` (no carrier) | **{s['out']}** |",
        f"| still `blocked` | **{s['blocked']}** |",
        f"| successor cards | {', '.join(s['successors'])} |",
        f"| §11 decisions still open on those successors | {', '.join(s['decisions_open']) or 'none'} |",
        f"| distinct evidence files | {len(s['evidence_files'])} |",
        f"| decompiled `ui/hud.gfx` scripts read | {s['hud_scripts']} |",
        f"| `out` rows this card owns, with a proof file | **{s['out_rows_with_proof']} / {s['out']}** |",
        "| later `out` rows (other cards) | not stored here - `--check` prints their census |",
        f"| problems | **{s['problems']}** |",
        "",
        "The dispositions live in two places, and this file is checked against both: the",
        "`T_ROWS.jsonl` ledger (generated by `t_rows.py build` from its `DISPO` table) and the",
        "`T6_HUD_CAMERA.md` tables (`status_audit.py` parses them directly). A row whose file",
        "disagrees with this table is a `--check` failure, not a footnote.",
        "",
        "## 1. Old row → new disposition → evidence",
        "",
        "| row | doc | was | now | successor(s) | §11 gate | primary evidence | feature codes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in p["rows"]:
        prim = r["evidence"][0]["file"] if r["evidence"] else "-"
        gate = ", ".join(f"{d['id']}{'' if d['resolved'] else ' (open)'}"
                         for d in r["decisions"]) or "-"
        L.append(f"| {r['id']} | {r['doc']} | {r['was']} | **{r['now']}** | "
                 f"{', '.join(r['successors']) or '—'} | {gate} | `{prim}` | {r['feature']} |")
    L += [
        "",
        "## 2. The evidence, row by row",
        "",
        "Every line below is re-read by `--check`. `needle` = the file still contains the string;",
        "`absent` = the file contains the anchor (proof the census surface was read) and none of",
        "the must-not words; `hud` = the same test over the decompiled `ui/hud.gfx`, searching the",
        "US spelling too and listing what the allow-list explains (the `CHAOS_REWARD_ARMORY` icon);",
        "`exists` = the built file is on disk (used where the alternative was citing this card's",
        "own row).",
        "",
    ]
    for r in p["rows"]:
        L += [f"### {r['id']} — {r['was']} → {r['now']}", ""]
        if r["split"]:
            L += [f"**Split:** {r['split']}", ""]
        L += [f"**Why:** {r['why']}", ""]
        for e in r["evidence"]:
            if e["kind"] == "needle":
                q = f"`{e['need']}`"
            elif e["kind"] == "absent":
                q = (f"anchor `{e['anchor']}`, must not name "
                     f"{', '.join('`' + w + '`' for w in e['must_not'])}")
            elif e["kind"] == "exists":
                q = "the file exists"
            else:
                q = "must not name " + ", ".join("`" + w + "`" for w in e["must_not"])
                if e.get("allow"):
                    q += "; allow-list " + ", ".join(
                        f"`{w}` \u2190 {', '.join(p for p in pats)}"
                        for w, pats in e["allow"].items())
            L += [f"- `{e['kind']}` {q} — {e['why']}", f"  - {'ok' if e['ok'] else 'FAIL'}: "
                  f"{e['detail']}"]
        L.append("")
    L += [
        "## 3. The rows that stay `out`, and the file that proves it",
        "",
        "| row | requirement | proof file | what it shows |",
        "|---|---|---|---|",
    ]
    for r in p["rows"]:
        if r["now"] != "out":
            continue
        prim = r["evidence"][0]
        L.append(f"| {r['id']} | {r['feature']} | `{prim['file']}` | {prim['why']} |")
    L += [
        "",
        "## 4. What this cannot prove",
        "",
        f"* The card's Done clause - \"no `out` row lacks a proof file\" - is verified here for the",
        f"  `out` rows this card re-decided ({s['out_rows_with_proof']}/{s['out']}). Rows other cards",
        "  wrote later are **not** this card's to prove: the shared ledger cannot be a",
        "  byte-compared artifact, so `--check` prints their census live (how many cite an existing",
        "  file path or a real G/T/B card id) and this file deliberately does not store it. The",
        "  wider reading of the sentence is therefore **not** asserted as met - it is measured by",
        "  that printed line, and a row that cites nothing belongs to the card that wrote it.",
        f"* An absence is an absence of **names in a decoded surface**, never of engine capability.",
        f"  The surfaces used here are named per row: the {s['vocab_types']}-type /",
        f"  {s['vocab_paths']:,}-path `VOCABULARY.md`, the {s['census_classes']}-class `ENTITIES.md`",
        f"  census, and the {s['hud_scripts']} decompiled scripts of `ui/hud.gfx`. A mechanism",
        "  implemented only in native code would not appear in any of them.",
        "* `ui/hud.gfx` is the **in-game** HUD movie. The other 28 `ui/*.gfx` movies in the index",
        "  are not decompiled, so a widget that lives in the frontend (`main.gfx`, `reward.gfx`)",
        "  would not be seen here. That is why the HUD rows are worded \"in the in-game HUD\".",
        "* A successor card is a **plan**, not a value: T-11…T-19 still have to write those rows,",
        "  and the D-2/D-3/D-7-gated ones stay `blocked: D-n` until the user answers §11.",
        "* Nothing here launches the game, writes a game file or touches `Builds/`.",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("dump", nargs="?", choices=["dump"], help="print the payload")
    a = ap.parse_args()
    p, census = derive()
    text = markdown(p)
    s = p["summary"]
    live = (f"later `out` rows: {census['cited']} of {census['total']} cite a proof (an existing "
            f"path or a real G/T/B card id), {len(census['unproven'])} do not"
            f" ({', '.join(census['unproven']) or 'none'})")
    if a.dump:
        print(json.dumps(p, indent=2, ensure_ascii=False))
        print(live)
        return 1 if p["problems"] else 0
    if a.write:
        with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
            json.dump(p, f, indent=2, ensure_ascii=False)
            f.write("\n")
        with open(OUT_MD, "w", encoding="utf-8", newline="\n") as f:
            f.write(text + "\n")
        print(f"wrote {rel(OUT_MD)} + {rel(OUT_JSON)} "
              f"({s['rows']} rows: {s['superseded']} superseded, {s['out']} out, "
              f"{s['blocked']} blocked; {s['out_rows_with_proof']}/{s['out']} out rows proven; "
              f"decisions open {', '.join(s['decisions_open']) or 'none'})")
        print(live)
        for prob in p["problems"]:
            print("FAIL", prob)
        return 1 if p["problems"] else 0
    if a.check:
        problems = list(p["problems"])
        if not os.path.exists(OUT_JSON) or not os.path.exists(OUT_MD):
            problems.append("T10_OPEN_ROWS.json/.md missing - run --write")
        else:
            if json.load(open(OUT_JSON, encoding="utf-8")) != p:
                problems.append("T10_OPEN_ROWS.json stale: the payload differs")
            if read(OUT_MD) != text + "\n":
                problems.append("T10_OPEN_ROWS.md stale: the text differs")
        if problems:
            for prob in problems:
                print("FAIL", prob)
            print(f"{len(problems)} problem(s)")
            return 1
        print(f"PASS: {s['rows']} rows ({s['superseded']} superseded, {s['out']} out, "
              f"{s['blocked']} blocked) | {s['out_rows_with_proof']}/{s['out']} out rows this card "
              f"owns carry a proof file | successors "
              f"{', '.join(s['successors'])} | decisions open "
              f"{', '.join(s['decisions_open']) or 'none'} | json match True, md match True")
        print(live)
        return 0
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
