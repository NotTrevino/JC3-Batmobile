# --------------------------------------------------------------------------- derived facts
def facts() -> dict:
    """Every count this file quotes, re-read from the record that owns it (R11)."""
    census = json.load(open(os.path.join(ROOT, G2, "FEATURE_CENSUS.json"), encoding="utf-8"))
    lights = json.load(open(os.path.join(BAT, "LIGHTS.json"), encoding="utf-8"))
    hud = json.load(open(os.path.join(ROOT, G2, "JC3_HUD_WEAPONS.json"), encoding="utf-8"))
    bmak = json.load(open(os.path.join(BAT, "WEAPONS.json"), encoding="utf-8"))
    t14 = json.load(open(os.path.join(WORK, "t14_lights.json"), encoding="utf-8"))
    vocab = read(os.path.join(ROOT, G2, "VOCABULARY.md")).splitlines()
    ent = read(os.path.join(ROOT, G2, "ENTITIES.md")).splitlines()
    types = sum(1 for l in vocab if l.startswith("## `"))
    paths = sum(1 for l in vocab if l.startswith("| `"))
    cls, in_cls = 0, False
    for l in ent:
        if l.startswith("## "):
            in_cls = l.startswith("## Class inventory")
            continue
        if in_cls and l.startswith("|") and not l.startswith("|---"):
            cls += 1
    cls -= 1                                   # the header row
    battle = int(lights["summary"]["by_type"].get("VEHLT_BattleModeLight") or 0)
    forensics = int(lights["summary"]["by_type"].get("VEHLT_ForensicsLight") or 0)
    battle_rows = [r["id"] for r in t14["rows"]
                   if r.get("bmak_type") == "VEHLT_BattleModeLight"]
    return {
        "weapon_ids": census["totals"]["weapon_ids"],
        "weapon_spellings": census["totals"]["weapon_id_spellings"],
        "armed_chassis": census["totals"]["armed_chassis"],
        "bmak_weapon_classes": bmak["counts"]["gadget_classes"],
        "vocab_types": types, "vocab_paths": paths, "census_classes": cls,
        "vocab": f"{types}-type / {paths:,}-path",
        "census": f"{cls}-class",
        "battle_entries": battle, "forensics_entries": forensics,
        "battle_rows": battle_rows, "battle_row_span": (f"{battle_rows[0]}-{battle_rows[-1]}"
                                                        if battle_rows else "-"),
        "hud_init_args": len(hud["init"]["params"]),
        "hud_update_args": len(hud["update"]["params"]),
    }


